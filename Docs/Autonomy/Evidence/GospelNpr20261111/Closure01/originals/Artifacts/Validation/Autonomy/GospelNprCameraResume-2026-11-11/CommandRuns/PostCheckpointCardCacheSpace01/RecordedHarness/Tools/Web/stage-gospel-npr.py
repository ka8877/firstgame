#!/usr/bin/env python3
"""Stage new Gospel NPR and the byte-identical protected Card product.

Builds/tests/Root review must already be real. Never builds, publishes, edits
the preserved Card tree, accepts unseen images or substitutes historical passes.
"""
from datetime import datetime, timezone
from pathlib import Path
import argparse
import importlib.util
import json
import os
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'Tools/Validation'))
from LivingRpgClassic import profile as RELEASE
from release_contract import contract, manifest_contract
from canon_release_evidence import (OUT, BUILD, STAGE, digest, regular, require, runtime,
                                    verify_builds, verify_browser, preserved_card)
from GospelNpr.card_baseline import summary as baseline_summary

SPEC = importlib.util.spec_from_file_location('npr_shared_stage_primitives', ROOT / 'Tools/Web/stage-canon.py')
SHARED = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SHARED)
MARKER = 'Generated by Tools/Web/stage-gospel-npr.py\n'
BUDGET = 985_000_000


def copy_regular(source, target, link=False):
    source = regular(source)
    target.parent.mkdir(parents=True, exist_ok=True)
    if link:
        try:
            os.link(source, target)
            return
        except OSError:
            pass
    shutil.copyfile(source, target)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=STAGE)
    args = parser.parse_args()
    require(RELEASE.NAME == 'gospel-npr' and RELEASE.CURRENT_GAMES == ('PathOfDawn',)
            and RELEASE.PRESERVED_GAMES == ('FantasyCards',), 'Explicit Gospel-only NPR source contract required')
    release = contract(RELEASE.NAME)
    require(release['preservedGames'] == ['FantasyCards'], 'Exact preserved Card release contract required')
    stage = args.output.absolute()
    require(stage == STAGE.absolute() and stage.resolve() == stage and stage.is_relative_to(ROOT / 'Artifacts')
            and stage != ROOT / 'Artifacts' and not any(item.is_symlink() for item in (stage, *stage.parents))
            and not stage.is_relative_to(OUT) and not OUT.is_relative_to(stage), 'Dedicated regular current NPR stage required')
    builds = verify_builds()
    require(set(builds['games']) == {'PathOfDawn'}, 'Only Gospel may be presented as a new build')
    reports = {'PathOfDawn': [verify_browser('PathOfDawn', mode) for mode in ('Desktop720', 'Mobile844')]}
    card = preserved_card()
    hero = regular(OUT / 'Portal/PathOfDawn.png')
    require(any(digest(hero) == shot['sha256'] for report in reports['PathOfDawn'] for shot in report['approvedOriginals']),
            'Gospel hero must be an actual current Root-reviewed NPR original')
    source = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    require(not subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True), 'Commit final source before staging')
    timestamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    if stage.exists():
        marker = regular(stage / '.firstgame-web-output')
        require(marker.read_text() == MARKER, 'Do not replace an unknown stage')
        stage.rename(stage.with_name(stage.name + '.previous-' + timestamp))
    OUT.mkdir(parents=True, exist_ok=True)
    ledger = OUT / 'generated-stage-storage.json'
    if ledger.exists():
        regular(ledger)
        ledger.rename(ledger.with_name('generated-stage-storage.previous-' + timestamp + '.json'))
    ledger.write_text(json.dumps({'status': 'prepared', 'artifactPath': str(stage), 'actualRoot': str(stage),
        'preparedUtc': datetime.now(timezone.utc).isoformat(), 'ownershipMarker': MARKER}, indent=2) + '\n')
    stage.mkdir(parents=True)
    (stage / '.firstgame-web-output').write_text(MARKER)
    (stage / '.nojekyll').write_text('')
    for name in ('index.html', 'site.css'):
        copy_regular(ROOT / 'Tools/Web' / name, stage / name)
    # Exact entire protected published Card tree, including existing notices.
    card_root = Path(card['runtimeRoot'])
    for name, expected in card['files'].items():
        original = regular(card_root / name)
        require(digest(original) == expected['sha256'] and original.stat().st_size == expected['bytes'], 'Protected Card source changed')
        SHARED.SAFETY.safe_public(original, name)
        copy_regular(original, stage / 'games/fantasy-cards' / name, link=True)
    copy_regular(ROOT / card['hero']['file'], stage / 'art/fantasy-cards.png')
    for name, original in runtime(BUILD / 'PathOfDawn/Web').items():
        SHARED.SAFETY.safe_public(original, name)
        copy_regular(original, stage / 'games/path-of-dawn' / name)
    notices = SHARED.notices('PathOfDawn')
    # Retained legacy Resources/media keep their actual existing attributions;
    # these notices make no claim that the new actor renders old sprite art.
    notices.update({
        'ClientMotion-SOURCE-NOTICE.txt': regular(ROOT / 'Tools/Art/ClientMotion/SOURCE-NOTICE.txt'),
        'Neutral-Characters-SOURCE-NOTICE.txt': regular(ROOT / 'Tools/Art/ClientMotionNeutral/SOURCE-NOTICE.txt'),
        'Flare-HD-CREDITS.txt': regular(ROOT / 'Tools/Research/ClientMotionCharacters/flare-art-src-CREDITS.txt'),
        'Flare-HD-LICENSE.txt': regular(ROOT / 'Tools/Research/ClientMotionCharacters/flare-art-src-LICENSE.txt'),
    })
    notices['GospelNpr-SOURCE-NOTICE.txt'] = regular(ROOT / 'Tools/Art/GospelNpr/SOURCE-NOTICE.txt')
    notices['GospelNpr/SOURCE-NOTICE.txt'] = notices['GospelNpr-SOURCE-NOTICE.txt']
    for name in (
        'source-manifest.json', 'actor-manifest.json',
        'Extracted/C-model.json', 'Extracted/F-model.json',
    ):
        notices['GospelNpr/' + name] = regular(ROOT / 'Tools/Art/GospelNpr' / name)
    for name in (
        'lilToon-LICENSE.txt', 'lilToon-THIRD-PARTY-NOTICES.md',
        'VRoid-sample-terms.html', 'VRM1-license.html',
        'nature-License.txt', 'ruins-License.txt', 'Quaternius-animation-License.txt',
        'quaternius-ultimate-stylized-nature.html', 'PolyHaven-license.html', 'index.json',
    ):
        notices['GospelNpr/Provenance/' + name] = regular(ROOT / 'Tools/Art/GospelNpr/Provenance' / name)
    for name, original in notices.items():
        copy_regular(original, stage / 'games/path-of-dawn/ThirdParty' / name)
    copy_regular(hero, stage / 'art/path-of-dawn.png')
    files = {}
    for original in sorted(stage.rglob('*')):
        require(not original.is_symlink(), 'No link may enter the stage')
        if original.is_file() and original.name != '.firstgame-web-output':
            name = original.relative_to(stage).as_posix()
            SHARED.SAFETY.safe_public(original, name)
            files[name] = digest(original)
    manifest = {'releaseProfile': RELEASE.NAME, 'currentTargets': ['Web'],
        'createdUtc': datetime.now(timezone.utc).isoformat(), 'publishReady': True,
        'gameRevisions': RELEASE.REVISIONS, 'contentVersions': release['contents'],
        'sourceCommit': source, 'sourceDirty': False, 'files': files,
        'browserProfiles': ['Desktop720', 'Mobile844'],
        'browserProfilesByGame': {'PathOfDawn': ['Desktop720', 'Mobile844'], 'FantasyCards': []},
        'browserReportRootsByGame': release['reportRoots'],
        'currentBuilds': builds, 'currentBrowserReports': reports,
        'preservedGameBaselines': {'FantasyCards': baseline_summary(card)},
        'incompleteBrowserRuns': [], 'adjudicatedBrowserReports': [], 'reusedBrowserEvidence': [],
        'siteBudgetBytesIncludingManifest': BUDGET}
    manifest_contract(manifest)
    raw = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode()
    complete = sum((stage / name).stat().st_size for name in files) + len(raw)
    require(complete < BUDGET, 'Complete staged site including manifest exceeds985MB')
    require(not subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True), 'Source changed during staging')
    require(baseline_summary(preserved_card()) == baseline_summary(card), 'Protected Card identity changed during staging')
    for name, expected in files.items():
        require(digest(stage / name) == expected, 'Staged bytes changed before completion')
    (stage / 'build-manifest.json').write_bytes(raw)
    print(json.dumps({'status': 'staged', 'files': len(files) + 1, 'bytes': complete,
                      'sourceCommit': source, 'artifactPath': str(stage), 'preservedCardSourceCommit': card['baselineProductSourceCommit']}))


if __name__ == '__main__':
    main()

