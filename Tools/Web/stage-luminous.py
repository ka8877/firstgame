#!/usr/bin/env python3
"""Stage the verified Gospel 2D player while preserving the deployed card game.

No build, browser, download or publish is performed. The prior complete HTTPS
snapshot, fresh current-player reports and explicit Root screenshot reviews are
required. Run after the final source commit; generated output lives in /tmp.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import importlib.util
import json
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess

from release_contract import LUMINOUS, manifest_contract

ROOT = Path(__file__).resolve().parents[2]
EVIDENCE = ROOT / 'Artifacts/Validation/Luminous'
ACTUAL = Path('/tmp/firstgame-luminous-staged-site')
LINK = ROOT / 'Artifacts/LuminousWebPlaytest'
MARKER = 'Generated by Tools/Web/stage-luminous.py\n'
PG_PREFIX = 'games/path-of-dawn/'
FM_PREFIX = 'games/fantasy-cards/'
REVISION = LUMINOUS['revisions']['PathOfDawn']


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(path):
    result = hashlib.sha256()
    with Path(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            result.update(block)
    return result.hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def reference(path):
    path = Path(path)
    return {'file': str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path),
            'bytes': path.stat().st_size, 'sha256': digest(path)}


def relative(name):
    require(isinstance(name, str) and name and '\\' not in name, 'Invalid public file name')
    path = PurePosixPath(name)
    require(not path.is_absolute() and '..' not in path.parts and str(path) == name, 'Unsafe public path: ' + name)
    return path


def regular(path, base):
    path, base = Path(path), Path(base).resolve()
    require(path.is_file() and not path.is_symlink() and path.resolve().is_relative_to(base),
            'Missing, linked or outside file: ' + str(path))
    require(not any(parent.is_symlink() for parent in path.parents if parent != base and parent.is_relative_to(base)),
            'Linked public file parent: ' + str(path))
    return path


def safe_public(path, name):
    parts = relative(name).parts
    forbidden = {'.git', '.aws', '.codex', '.pki', '.config', '.ssh', 'credentials', 'Secrets', 'UserSettings'}
    require(not any(part in forbidden or 'DoNotShip' in part or 'DontShip' in part for part in parts),
            'Private/debug path in public output: ' + name)
    require(Path(name).suffix.lower() not in {'.cs', '.py', '.log', '.map', '.pdb', '.mdb', '.ulf', '.key', '.lic'}
            and not parts[-1].startswith('.env') and '.symbols.' not in parts[-1], 'Non-runtime public file: ' + name)
    require(path.stat().st_size < 100_000_000, 'Public file exceeds the hosting limit: ' + name)
    with path.open('rb') as stream:
        prefix = stream.read(512)
    require(not prefix.startswith(b'version https://git-lfs.github.com/spec/v1'), 'Unresolved LFS pointer: ' + name)
    require(not re.match(br'\s*-----BEGIN (?:RSA |EC |OPENSSH )?PRIVATE KEY-----', prefix),
            'Private-key file in public output: ' + name)


def runtime_files(player):
    files = {}
    for path in sorted(player.rglob('*')):
        if not path.is_file():
            continue
        name = path.relative_to(player).as_posix()
        parts = relative(name).parts
        if name != 'index.html' and parts[0] not in ('Build', 'StreamingAssets', 'TemplateData'):
            continue
        regular(path, player)
        safe_public(path, name)
        files[name] = path
    require('index.html' in files and any(name.startswith('Build/') for name in files) and len(files) >= 5,
            'Complete new Web runtime is missing')
    return files


def verify_preserved(folder):
    folder = folder.resolve()
    manifest_path, record_path = folder / 'build-manifest.json', folder / 'preservation-record.json'
    regular(manifest_path, folder)
    regular(record_path, folder)
    manifest, record = read(manifest_path), read(record_path)
    require(record['manifestSHA256'] == digest(manifest_path), 'Preserved deployment manifest changed')
    require(manifest_contract(manifest)['name'] == 'restoration' and manifest['sourceDirty'] is False
            and manifest['gameRevisions']['FantasyCards'] == LUMINOUS['revisions']['FantasyCards'],
            'The exact previously deployed card revision is required')
    rows = {item['file']: item for item in record['publicFiles']}
    require(set(rows) == set(manifest['files']) and len(rows) == len(record['publicFiles']),
            'Preserved complete public file set differs')
    for name, expected in manifest['files'].items():
        path = regular(folder / str(relative(name)), folder)
        safe_public(path, name)
        row = rows[name]
        require(row['status'] == 200 and row['bytes'] == path.stat().st_size
                and row['sha256'] == expected == digest(path), 'Preserved public bytes changed: ' + name)
    keep = {name: rows[name] for name in rows if name.startswith(FM_PREFIX) or name == 'art/fantasy-cards.png'}
    require(len(keep) >= 10 and 'art/fantasy-cards.png' in keep, 'Preserved card files/preview missing')
    return manifest, record, keep


def verify_player(player):
    evidence_path = regular(player / 'BuildEvidence.txt', player)
    evidence = dict(line.split(': ', 1) for line in evidence_path.read_text().splitlines() if ': ' in line)
    require(evidence.get('Revision') == REVISION and evidence.get('Content') == 'gospel-0.1.0'
            and evidence.get('Target') == 'WebGL' and evidence.get('Result') == 'Succeeded'
            and evidence.get('Errors') == '0' and evidence.get('LegacyResourcesRestored') == 'true',
            'Successful current Gospel build with restored legacy resources is required')
    inputs_path = regular(player / 'BuildInputs.json', player)
    spec = importlib.util.spec_from_file_location('luminous_stage_source_binding', ROOT / 'Tools/Validation/restoration_source_binding.py')
    binding = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(binding)
    value = read(inputs_path)
    require(value['game'] == 'PathOfDawn' and binding.verify(value) == evidence.get('SourceFingerprint'),
            'Current authored inputs differ from the actual new Web build')
    return runtime_files(player), {'buildEvidence': reference(evidence_path), 'buildInputs': reference(inputs_path),
                                  'sourceFingerprint': value['fingerprint']}


def shot_path(shot):
    name = shot.get('path', shot.get('file'))
    require(isinstance(name, str), 'Screenshot needs its original path/file')
    path = Path(name)
    return path if path.is_absolute() else ROOT / path


def verify_report(report_path, profile, runtime):
    regular(report_path, EVIDENCE)
    report = read(report_path)
    require(report.get('game') == 'PathOfDawn' and report.get('revision') == REVISION
            and report.get('suite') == 'gospel-luminous-real-input-v1' and report.get('status') == 'passed'
            and report.get('checks') and all(item.get('passed') is True for item in report['checks']),
            'Every current actual browser check must pass: ' + profile)
    viewport = report.get('interactionViewport', {})
    require((viewport.get('width'), viewport.get('height')) == ((1280, 720) if profile == 'Desktop720' else (844, 390)),
            'Wrong current browser interaction viewport: ' + profile)
    current = {name: {'file': name, 'bytes': path.stat().st_size, 'sha256': digest(path)} for name, path in runtime.items()}
    recorded = report.get('buildFingerprint', {}).get('files', [])
    require(len(recorded) == len(current) and {item['file'] for item in recorded} == set(current),
            'Complete current report runtime fingerprint required: ' + profile)
    for item in recorded:
        require(all(item.get(key) == value for key, value in current[item['file']].items()),
                'Reported runtime changed: ' + item['file'])
    review = report.get('visualReview', {})
    require(review.get('status') == 'approved' and review.get('reviewer') in ('root', '/root')
            and review.get('reviewedUtc') and len(review.get('screenshots', [])) >= 2,
            'Fresh explicit Root review of current original frames is required: ' + profile)
    reviewed_runtime = review.get('runtimeFiles', [])
    require(len(reviewed_runtime) == len(current) and {item['file'] for item in reviewed_runtime} == set(current),
            'Root review must bind the complete current runtime set: ' + profile)
    for item in reviewed_runtime:
        require(all(item.get(key) == value for key, value in current[item['file']].items()),
                'Root-reviewed runtime changed: ' + item['file'])
    originals = report.get('screenshots', [])
    approved = []
    for shot in review['screenshots']:
        path = regular(shot_path(shot), report_path.parent)
        require(digest(path) == shot.get('sha256') and any(shot_path(original).resolve() == path.resolve()
                and original.get('sha256') == shot['sha256'] for original in originals),
                'Root-reviewed image is not an unchanged current original: ' + str(path))
        approved.append({'file': str(path.relative_to(ROOT)), 'sha256': shot['sha256']})
    require(len({item['file'] for item in approved}) == len(approved), 'Duplicate reviewed originals')
    return {'profile': profile, **reference(report_path), 'reviewer': review['reviewer'],
            'reviewedUtc': review['reviewedUtc'], 'approvedOriginals': approved}


def prepare_output():
    if LINK.exists() or LINK.is_symlink():
        require(LINK.is_symlink() and LINK.readlink() == ACTUAL, 'Unexpected Luminous artifact path')
    if ACTUAL.exists():
        require(ACTUAL.is_dir() and not ACTUAL.is_symlink() and (ACTUAL / '.firstgame-web-output').read_text() == MARKER,
                'Refusing an output root without the exact Luminous ownership marker')
        archived = ACTUAL.with_name(ACTUAL.name + '.previous-' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ'))
        ACTUAL.rename(archived)
    EVIDENCE.mkdir(parents=True, exist_ok=True)
    # Written before creating the storage link. This records generated storage,
    # not browser approval or permission to use an arbitrary outside directory.
    ledger = {'status': 'prepared', 'artifactPath': str(LINK), 'actualRoot': str(ACTUAL),
              'preparedUtc': datetime.now(timezone.utc).isoformat(), 'ownershipMarker': MARKER,
              'scope': 'Generated staged public files only; authored inputs and prior public snapshot retained.'}
    (EVIDENCE / 'generated-stage-storage.json').write_text(json.dumps(ledger, indent=2) + '\n')
    ACTUAL.mkdir()
    (ACTUAL / '.firstgame-web-output').write_text(MARKER)
    if not LINK.is_symlink():
        LINK.symlink_to(ACTUAL, target_is_directory=True)
    return ACTUAL


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--build-root', type=Path, default=Path('/tmp/firstgame-luminous-builds'))
    parser.add_argument('--preserved', type=Path, default=Path('/tmp/firstgame-luminous-preserved-public'))
    args = parser.parse_args()
    player, preserved = (args.build_root / 'PathOfDawn/Web').resolve(), args.preserved.resolve()
    prior, preservation, card_files = verify_preserved(preserved)
    runtime, build = verify_player(player)
    reports = [verify_report(EVIDENCE / profile / 'PathOfDawn/report.json', profile, runtime)
               for profile in ('Desktop720', 'Mobile844')]
    hero = regular(EVIDENCE / 'Portal/PathOfDawn.png', EVIDENCE)
    require(any(digest(hero) == shot['sha256'] for report in reports for shot in report['approvedOriginals']),
            'Portal art must be an unchanged explicitly reviewed current game original')
    world_notice = regular(ROOT / 'Games/PathOfDawn/Assets/Resources/Art/GospelLuminous/World/SOURCE-NOTICE.txt', ROOT)
    require('Unity Companion License' in world_notice.read_text() and 'v1.4' in world_notice.read_text(),
            'Complete original world copyright/license notice is required')
    notices = {
        'FirstGameKorean-OFL.txt': ROOT / 'Games/PathOfDawn/Assets/Resources/Fonts/OFL.txt',
        'LiberationSans-OFL.txt': ROOT / 'Games/PathOfDawn/Assets/TextMesh Pro/Fonts/LiberationSans - OFL.txt',
        'Pretendard-OFL.txt': ROOT / 'Games/PathOfDawn/Assets/Resources/Fonts/Pretendard-OFL.txt',
        'Music-NOTICE.txt': ROOT / 'Tools/Audio/MUSIC-NOTICE.txt',
        'Ink-LICENCE.md': ROOT / 'Games/PathOfDawn/Packages/com.inkle.ink-unity-integration/LICENCE.md',
        'Scripture-NOTICE.txt': ROOT / 'Tools/Data/Gospel/SCRIPTURE-NOTICE.txt',
        'LostCrypt-World-SOURCE-NOTICE.txt': world_notice,
        'LuminousActors-SOURCE-NOTICE.txt': ROOT / 'Games/PathOfDawn/Assets/Resources/Art/GospelLuminous/Actors/SOURCE-NOTICE.txt',
        'LuminousActors-UnityCompanionLicense.txt': ROOT / 'Games/PathOfDawn/Assets/Resources/Art/GospelLuminous/Actors/UnityCompanionLicense.txt',
    }
    for path in notices.values():
        regular(path, ROOT)
    source_commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    require(re.fullmatch(r'[0-9a-f]{40}', source_commit)
            and not subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True),
            'Commit the final source and validation notes before staging')
    # These exact old phrases come from the independently verified deployed
    # portal. No card panel/copy/style is replaced with a different edition.
    html = (preserved / 'index.html').read_text()
    replacements = {
        '예수님의 길 3D 성경 여정.': '예수님의 길 2D 빛의 숲 체험판.',
        '싱글 플레이 · 3D 성경 여정': '싱글 플레이 · 2D 빛의 숲',
        '탄생의 말씀을 읽고 성전 뜰을 걸으며, 새 카툰 인물과 대화하며 성경 본문을 함께 읽는 첫 구간. 인물·소지품·안내도를 열어 여정을 살펴보세요.':
            '빛과 안개가 흐르는 올리브 숲을 걷는 새 2D 장면. 관절형 인물의 걷기·달리기·점프와 소지품을 살펴보고, 원할 때 말씀을 읽어보세요.',
        '원작 규칙 기반 싱글 카드전 · 3D 성경 여정 첫 구간': '원작 규칙 기반 싱글 카드전 · 2D 빛의 숲 첫 장면',
        '<time datetime="2026-10-27">2026.10.27</time>': '<time datetime="2026-10-28">2026.10.28</time>',
    }
    for old, new in replacements.items():
        require(html.count(old) == 1, 'Known preserved portal wording changed: ' + old)
        html = html.replace(old, new)
    output = prepare_output()
    for name in prior['files']:
        if name.startswith(PG_PREFIX) or name == 'art/path-of-dawn.png':
            continue
        target = output / str(relative(name))
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(preserved / name, target)
    (output / 'index.html').write_text(html)
    for name, source in runtime.items():
        target = output / PG_PREFIX / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    for name, source in notices.items():
        target = output / PG_PREFIX / 'ThirdParty' / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    shutil.copyfile(hero, output / 'art/path-of-dawn.png')
    for name, row in card_files.items():
        require((output / name).stat().st_size == row['bytes'] and digest(output / name) == row['sha256'],
                'Untouched card public file changed: ' + name)
    published_cards = {path.relative_to(output).as_posix() for path in (output / 'games/fantasy-cards').rglob('*') if path.is_file()}
    require(published_cards == {name for name in card_files if name.startswith(FM_PREFIX)}, 'Card runtime file set changed')
    files = {}
    for path in sorted(output.rglob('*')):
        if not path.is_file() or path.name == '.firstgame-web-output':
            continue
        regular(path, output)
        name = path.relative_to(output).as_posix()
        safe_public(path, name)
        files[name] = digest(path)
    manifest = {
        'releaseProfile': 'luminous', 'createdUtc': datetime.now(timezone.utc).isoformat(), 'publishReady': True,
        'gameRevisions': dict(LUMINOUS['revisions']), 'contentVersions': dict(LUMINOUS['contents']),
        'sourceCommit': source_commit, 'sourceDirty': False, 'files': files,
        'browserProfiles': ['Desktop720', 'Mobile844'],
        'browserProfilesByGame': {'FantasyCards': [], 'PathOfDawn': ['Desktop720', 'Mobile844']},
        'browserReportRootsByGame': dict(LUMINOUS['reportRoots']), 'currentGospelBrowserReports': reports,
        'currentGospelBuild': build, 'incompleteBrowserRuns': [], 'adjudicatedBrowserReports': [],
        'reusedBrowserEvidence': [{'game': 'FantasyCards', 'revision': LUMINOUS['revisions']['FantasyCards'],
            'reason': 'Exact previously deployed runtime/art/notices retained; no new card build or browser pass is claimed.',
            'preservationRecord': reference(preserved / 'preservation-record.json')}],
        'preservedPublic': {'sourceCommit': prior['sourceCommit'], 'manifest': reference(preserved / 'build-manifest.json'),
            'record': reference(preserved / 'preservation-record.json'), 'files': list(card_files.values())},
    }
    manifest_contract(manifest)
    (output / 'build-manifest.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'status': 'staged', 'releaseProfile': 'luminous', 'files': len(files),
        'bytes': sum((output / name).stat().st_size for name in files), 'preservedCardFiles': len(card_files),
        'sourceCommit': source_commit, 'actualRoot': str(output), 'artifactPath': str(LINK)}))


if __name__ == '__main__':
    try:
        main()
    except (AssertionError, KeyError, ValueError, OSError, subprocess.CalledProcessError) as error:
        raise SystemExit('Luminous staging refused: ' + str(error))
