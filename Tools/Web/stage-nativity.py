#!/usr/bin/env python3
"""Stage both current players only after exact-source tests and Root frame review."""
from datetime import datetime,timezone
import importlib.util,json,os,shutil,subprocess,sys
from pathlib import Path
from release_contract import NATIVITY,manifest_contract
ROOT=Path(__file__).resolve().parents[2]
sys.path.insert(0,str(ROOT/'Tools/Validation'))
from nativity_release_evidence import OUT,BUILD,REVISIONS,require,read,ref,digest,runtime,verify_builds,verify_browser
spec=importlib.util.spec_from_file_location('renewal_stage_safety',ROOT/'Tools/Web/stage-luminous.py');BASE=importlib.util.module_from_spec(spec);spec.loader.exec_module(BASE)
ACTUAL=Path('/tmp/firstgame-nativity-staged-site');LINK=ROOT/'Artifacts/NativityWebPlaytest';MARKER='Generated by Tools/Web/stage-nativity.py\n'
GAMES={'FantasyCards':'fantasy-cards','PathOfDawn':'path-of-dawn'}

def notices(game):
 project=ROOT/'Games'/game
 result={'FirstGameKorean-OFL.txt':project/'Assets/Resources/Fonts/OFL.txt','LiberationSans-OFL.txt':project/'Assets/TextMesh Pro/Fonts/LiberationSans - OFL.txt','Pretendard-OFL.txt':project/'Assets/Resources/Fonts/Pretendard-OFL.txt','Music-NOTICE.txt':ROOT/'Tools/Audio/MUSIC-NOTICE.txt'}
 if game=='FantasyCards':
  result.update({'ClassicCards-SOURCE-NOTICE.txt':ROOT/'Tools/Art/ClassicCards/SOURCE-NOTICE.txt','Revival-SOURCE-NOTICE.txt':ROOT/'Tools/Research/FmRevival/SOURCE-NOTICE.txt','Restoration-SOURCE-NOTICE.txt':ROOT/'Tools/Audio/Restoration/SOURCE-NOTICE.txt','Renewal-Audio-SOURCE-NOTICE.txt':ROOT/'Tools/Audio/Renewal/SOURCE-NOTICE.txt'})
 else:
  result.update({'Ink-LICENCE.md':project/'Packages/com.inkle.ink-unity-integration/LICENCE.md','Scripture-NOTICE.txt':ROOT/'Tools/Data/Gospel/SCRIPTURE-NOTICE.txt','LostCrypt-World-SOURCE-NOTICE.txt':project/'Assets/Resources/Art/GospelLuminous/World/SOURCE-NOTICE.txt','LuminousActors-SOURCE-NOTICE.txt':project/'Assets/Resources/Art/GospelLuminous/Actors/SOURCE-NOTICE.txt','LuminousActors-UnityCompanionLicense.txt':project/'Assets/Resources/Art/GospelLuminous/Actors/UnityCompanionLicense.txt'})
  result.update({'Pilgrimage-Art-SOURCE-NOTICE.txt':ROOT/'Tools/Art/GospelPilgrimage/SOURCE-NOTICE.txt',
                 'AuthoredProps-SOURCE-NOTICE.txt':ROOT/'Tools/Art/GospelAuthoredProps/SOURCE-NOTICE.txt',
                 'Well-Props-SOURCE-NOTICE.txt':ROOT/'Tools/Art/GospelWell/SOURCE-NOTICE.txt',
                 'Radiance-Art-SOURCE-NOTICE.txt':ROOT/'Tools/Art/GospelRadiance/SOURCE-NOTICE.txt',
                 'Chronicle-Art-SOURCE-NOTICE.txt':ROOT/'Tools/Art/GospelChronicle/SOURCE-NOTICE.txt',
                 'NewtonsoftJson-LICENSE.md':ROOT/'Tools/ThirdParty/NewtonsoftJson/LICENSE.md',
                 'NewtonsoftJson-ThirdPartyNotices.md':ROOT/'Tools/ThirdParty/NewtonsoftJson/Third Party Notices.md',
                 'Radiance-Rendering-SOURCE-NOTICE.txt':project/'Assets/Resources/Art/GospelRadiance/Rendering/SOURCE-NOTICE.txt',
                 'Radiance-Shaders-UnityCompanionLicense.txt':project/'Assets/Resources/Art/GospelLuminous/Actors/UnityCompanionLicense.txt'})
 for folder in (ROOT/'Tools/Data/Renewal',ROOT/'Tools/Art/Renewal',ROOT/'Tools/Art/GospelRenewal'):
  if folder.exists():
   for p in folder.rglob('*NOTICE*.txt'):
    if p.is_file():result['Renewal-'+folder.name+'-'+p.name]=p
 result['Reprise-Audio-SOURCE-NOTICE.txt']=ROOT/'Tools/Audio/Reprise/SOURCE-NOTICE.txt'
 result['Restage-Art-SOURCE-NOTICE.txt']=ROOT/'Tools/Art/Restage/SOURCE-NOTICE.txt'
 result['Nativity-Art-SOURCE-NOTICE.txt']=ROOT/'Tools/Art/Nativity/SOURCE-NOTICE.txt'
 if game=='PathOfDawn':
  result['Nativity-Audio-SOURCE-NOTICE.txt']=ROOT/'Tools/Audio/Nativity/SOURCE-NOTICE.txt'
  result['Nativity-Voice-SOURCE-NOTICE.txt']=ROOT/'Tools/Voice/Nativity/SOURCE-NOTICE.txt'
 result['FluidR3-LICENSE.txt']=ROOT/'Tools/Audio/FluidR3-LICENSE.txt'
 if game=='PathOfDawn': result['Storybook-Art-SOURCE-NOTICE.txt']=ROOT/'Tools/Art/GospelStorybook/SOURCE-NOTICE.txt'
 for p in result.values():require(p.is_file(),'Required current notice missing: '+str(p))
 return result

def main():
 builds=verify_builds();reports={game:[verify_browser(game,profile) for profile in ('Desktop720','Mobile844')] for game in GAMES}
 heroes={game:OUT/'Portal'/f'{game}.png' for game in GAMES}
 for game,hero in heroes.items():require(hero.is_file() and any(digest(hero)==s['sha256'] for r in reports[game] for s in r['approvedOriginals']),'Current portal original must be Root-reviewed: '+game)
 source=subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip()
 require(not subprocess.check_output(['git','status','--porcelain'],cwd=ROOT,text=True),'Commit final source before staging')
 if LINK.exists() or LINK.is_symlink():require(LINK.is_symlink() and LINK.readlink()==ACTUAL,'Unexpected staging artifact')
 if ACTUAL.exists():
  require((ACTUAL/'.firstgame-web-output').read_text()==MARKER and not ACTUAL.is_symlink(),'Unexpected staging root')
  ACTUAL.rename(ACTUAL.with_name(ACTUAL.name+'.previous-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')))
 OUT.mkdir(parents=True,exist_ok=True)
 (OUT/'generated-stage-storage.json').write_text(json.dumps({'status':'prepared','artifactPath':str(LINK),'actualRoot':str(ACTUAL),'preparedUtc':datetime.now(timezone.utc).isoformat(),'ownershipMarker':MARKER},indent=2)+'\n')
 ACTUAL.mkdir();(ACTUAL/'.firstgame-web-output').write_text(MARKER);(ACTUAL/'.nojekyll').write_text('')
 if not LINK.is_symlink():LINK.symlink_to(ACTUAL,target_is_directory=True)
 for n in ('index.html','site.css'):shutil.copyfile(ROOT/'Tools/Web'/n,ACTUAL/n)
 (ACTUAL/'art').mkdir()
 for game,slug in GAMES.items():
  for name,p in runtime(BUILD/game/'Web').items():
   BASE.safe_public(p,name);target=ACTUAL/'games'/slug/name;target.parent.mkdir(parents=True,exist_ok=True)
   # The 15,350 card fronts are immutable and byte-bound before staging.
   # Share their existing inode on this task volume rather than making a third
   # 750MB copy; a different filesystem safely falls back to an ordinary copy.
   if game=='FantasyCards' and name.startswith('StreamingAssets/Cards/'):
    try:os.link(p,target)
    except OSError:shutil.copyfile(p,target)
   else:shutil.copyfile(p,target)
  folder=ACTUAL/'games'/slug/'ThirdParty';folder.mkdir()
  for name,p in notices(game).items():shutil.copyfile(p,folder/name)
  shutil.copyfile(heroes[game],ACTUAL/'art'/f'{slug}.png')
 files={}
 for p in sorted(ACTUAL.rglob('*')):
  if p.is_file() and p.name!='.firstgame-web-output':
   name=p.relative_to(ACTUAL).as_posix();BASE.safe_public(p,name);files[name]=digest(p)
 total_bytes=sum((ACTUAL/n).stat().st_size for n in files)
 manifest={'releaseProfile':'nativity','currentTargets':NATIVITY['currentTargets'],'createdUtc':datetime.now(timezone.utc).isoformat(),'publishReady':True,'gameRevisions':REVISIONS,'contentVersions':NATIVITY['contents'],'sourceCommit':source,'sourceDirty':False,'files':files,'browserProfiles':['Desktop720','Mobile844'],'browserProfilesByGame':{g:['Desktop720','Mobile844'] for g in GAMES},'browserReportRootsByGame':NATIVITY['reportRoots'],'currentBuilds':builds,'currentBrowserReports':reports,'incompleteBrowserRuns':[],'adjudicatedBrowserReports':[],'reusedBrowserEvidence':[],'siteBudgetBytesIncludingManifest':985_000_000}
 manifest_contract(manifest);(ACTUAL/'build-manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
 complete_bytes=total_bytes+(ACTUAL/'build-manifest.json').stat().st_size
 require(complete_bytes < 985_000_000,'Complete staged site including manifest exceeds985MB budget; preserve source pixels and optimize only if needed before publication')
 print(json.dumps({'status':'staged','files':len(files)+1,'bytes':complete_bytes,'bytesExcludingManifest':total_bytes,'sourceCommit':source,'artifactPath':str(LINK)}))
if __name__=='__main__':main()
