def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path(os.environ.get(
        'FIRSTGAME_STAGE_ROOT', str(RELEASE.STAGE))))
    args = parser.parse_args()
    stage = args.output.absolute()
    artifacts = ROOT / 'Artifacts'
    require(stage != artifacts and stage.is_relative_to(artifacts)
            and stage.resolve() == stage and not any(path.is_symlink() for path in (stage, *stage.parents)),
            'Canon stage must be a regular directory inside Artifacts')
    require(not stage.is_relative_to(OUT) and not OUT.is_relative_to(stage), 'Stage and validation evidence must be separate')
    release = contract(RELEASE.NAME)
    require(REVISIONS == release['revisions'] and release.get('preservedGames') == [], 'Current two-game Canon contract required')
    builds = verify_builds()
    reports = {game: [verify_browser(game, profile) for profile in ('Desktop720', 'Mobile844')] for game in GAMES}
    heroes = {game: OUT / 'Portal' / (game + '.png') for game in GAMES}
    for game, hero in heroes.items():
        require(hero.is_file() and not hero.is_symlink() and any(digest(hero) == shot['sha256']
            for report in reports[game] for shot in report['approvedOriginals']),
            'Current portal image must be an actual Root-reviewed original: ' + game)
    source = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    require(not subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True), 'Commit final source before staging')
    stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    if stage.exists():
        marker = stage / '.firstgame-web-output'
        require(stage.is_dir() and marker.is_file() and not marker.is_symlink() and marker.read_text() == MARKER,
                'Refusing to replace an unknown staging directory')
        stage.rename(stage.with_name(stage.name + '.previous-' + stamp))
    OUT.mkdir(parents=True, exist_ok=True)
    ledger = OUT / 'generated-stage-storage.json'
    if ledger.exists():
        require(ledger.is_file() and not ledger.is_symlink(), 'Unexpected prior stage ledger')
        ledger.rename(ledger.with_name('generated-stage-storage.previous-' + stamp + '.json'))
    ledger.write_text(json.dumps({'status': 'prepared', 'artifactPath': str(stage), 'actualRoot': str(stage),
        'preparedUtc': datetime.now(timezone.utc).isoformat(), 'ownershipMarker': MARKER}, indent=2) + '\n')
    stage.mkdir(parents=True)
    (stage / '.firstgame-web-output').write_text(MARKER)
    (stage / '.nojekyll').write_text('')
    for name in ('index.html', 'site.css'):
        shutil.copyfile(ROOT / 'Tools/Web' / name, stage / name)
    (stage / 'art').mkdir()
    for game, slug in GAMES.items():
        for name, path in runtime(BUILD / game / 'Web').items():
            SAFETY.safe_public(path, name)
            require(not path.is_symlink() and not any(parent.is_symlink() for parent in path.parents), 'Runtime links are forbidden')
            target = stage / 'games' / slug / name
            target.parent.mkdir(parents=True, exist_ok=True)
            if game == 'FantasyCards' and name.startswith('StreamingAssets/Cards/'):
                try:
                    os.link(path, target)
                except OSError:
                    shutil.copyfile(path, target)
            else:
                shutil.copyfile(path, target)
        folder = stage / 'games' / slug / 'ThirdParty'
        folder.mkdir()
        for name, path in notices(game).items():
            shutil.copyfile(path, folder / name)
        shutil.copyfile(heroes[game], stage / 'art' / (slug + '.png'))
    files = {}
    for path in sorted(stage.rglob('*')):
        require(not path.is_symlink(), 'No link may enter the public stage')
        if path.is_file() and path.name != '.firstgame-web-output':
            name = path.relative_to(stage).as_posix()
            SAFETY.safe_public(path, name)
            files[name] = digest(path)
    total = sum((stage / name).stat().st_size for name in files)
    manifest = {'releaseProfile': RELEASE.NAME, 'currentTargets': release['currentTargets'],
        'createdUtc': datetime.now(timezone.utc).isoformat(), 'publishReady': True,
        'gameRevisions': REVISIONS, 'contentVersions': release['contents'],
        'sourceCommit': source, 'sourceDirty': False, 'files': files,
        'browserProfiles': ['Desktop720', 'Mobile844'],
        'browserProfilesByGame': {game: ['Desktop720', 'Mobile844'] for game in GAMES},
        'browserReportRootsByGame': {game: str(OUT.relative_to(ROOT)) for game in GAMES},
        'currentBuilds': builds, 'currentBrowserReports': reports,
        'incompleteBrowserRuns': [], 'adjudicatedBrowserReports': [], 'reusedBrowserEvidence': [],
        'siteBudgetBytesIncludingManifest': BUDGET}
    manifest_contract(manifest)
    raw = (json.dumps(manifest, ensure_ascii=False, indent=2) + '\n').encode()
    complete = total + len(raw)
    require(complete < BUDGET, 'Complete staged site including manifest exceeds985MB; original quality/content must be preserved')
    require(not subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True), 'Source changed during staging')
    for name, expected in files.items():
        require(digest(stage / name) == expected, 'Staged bytes changed before completion: ' + name)
    (stage / 'build-manifest.json').write_bytes(raw)
    print(json.dumps({'status': 'staged', 'files': len(files) + 1, 'bytes': complete,
        'bytesExcludingManifest': total, 'sourceCommit': source, 'artifactPath': str(stage)}))


if __name__ == '__main__':
    main()
