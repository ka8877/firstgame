def core_attributes(path):
    value = path.lstat()
    require(stat.S_ISREG(value.st_mode), 'A current proof core original must be regular')
    return {'dev': value.st_dev, 'ino': value.st_ino, 'bytes': value.st_size,
            'mode': stat.S_IMODE(value.st_mode), 'uid': value.st_uid, 'gid': value.st_gid,
            'mtimeNs': value.st_mtime_ns, 'ctimeNs': value.st_ctime_ns,
            'blocks': value.st_blocks, 'nlink': value.st_nlink}


def verified_current_core_sources(builds):
    """Sharp-only storage aliases; original proof inodes are never replaced."""
    result = {}
    for game in GAMES:
        reference = builds['games'][game]['proof']
        proof_path = PROOF_ROOT / (game + '-Web/build-proof-index.json')
        require((ROOT / reference['file']) == proof_path and proof_path.is_file()
                and not any(path.is_symlink() for path in (proof_path, *proof_path.parents))
                and proof_path.stat().st_size == reference['bytes'] and digest(proof_path) == reference['sha256'],
                'Exact independently retained current proof index required for core sharing')
        proof = json.loads(proof_path.read_bytes())
        require(proof.get('status') == 'preserved' and proof.get('game') == game
                and proof.get('revision') == REVISIONS[game] and proof.get('reportedBuildExitCode') == 0
                and proof.get('sourceFingerprint') == builds['games'][game]['native']['sourceFingerprint']
                and proof.get('originalBuildFolder') == str(BUILD / game / 'Web')
                and proof.get('runtimeByteIdentityBeforeAfter') is True and proof.get('coreRuntimeBytesCopied') is True,
                'Current successful immutable core proof required')
        core = proof.get('coreRuntimeFiles', [])
        suffixes = ('.data.unityweb', '.wasm.unityweb', '.framework.js.unityweb', '.loader.js')
        require(len(core) == 5 and len({row['file'] for row in core}) == 5
                and sum(row['file'] == 'index.html' for row in core) == 1
                and all(sum(row['file'].endswith(suffix) for row in core) == 1 for suffix in suffixes),
                'Only index and the four exact current Build core files may share proof inodes')
        result[game] = {}
        for row in core:
            name = row['file']
            require(name == 'index.html' or (len(Path(name).parts) == 2 and Path(name).parts[0] == 'Build')
                    and '..' not in Path(name).parts, 'Unsafe proof core name')
            require(row in proof['completeRuntimeFiles']
                    and {'file': 'Runtime/' + name, 'bytes': row['bytes'], 'sha256': row['sha256']} in proof['copiedOriginals'],
                    'Core must bind an independently copied original, not a runtime pointer')
            source = proof_path.parent / 'Runtime' / name
            require(not any(path.is_symlink() for path in (source, *source.parents)), 'No proof runtime symlinks')
            before = core_attributes(source)
            require(before['bytes'] == row['bytes'] and before['nlink'] >= 1
                    and digest(source) == row['sha256'] and core_attributes(source) == before,
                    'Actual original proof core bytes/attributes differ')
            result[game][name] = {'source': source, 'expected': row, 'before': before,
                                  'proof': reference}
    return result


def link_current_core(value, build_path, target, ledger):
    source, expected, before = value['source'], value['expected'], value['before']
    require(core_attributes(source) == before and source.stat().st_dev == target.parent.stat().st_dev
            and digest(source) == expected['sha256'] and build_path.stat().st_size == expected['bytes']
            and digest(build_path) == expected['sha256'] and not os.path.lexists(target),
            'Exact current build/proof bytes and same-disk new target required')
    entry = {'source': str(source), 'target': str(target), 'proof': value['proof'],
             'expected': expected, 'sourceBefore': before, 'status': 'intent-before-link'}
    current = json.loads(ledger.read_bytes())
    current.setdefault('immutableProofCoreLinks', []).append(entry)
    ledger.write_text(json.dumps(current, indent=2) + '\n')
    os.link(source, target, follow_symlinks=False)
    after, linked = core_attributes(source), core_attributes(target)
    require(after == linked and all(after[key] == before[key] for key in before if key not in ('nlink', 'ctimeNs'))
            and after['nlink'] == before['nlink'] + 1 and after['ctimeNs'] >= before['ctimeNs']
            and digest(target) == digest(source) == expected['sha256'],
            'Only source link count/ctime may change; new stage must share the unchanged original inode')
    entry.update(status='verified-linked-original-retained', sourceAfter=after, targetAfter=linked)
    ledger.write_text(json.dumps(current, indent=2) + '\n')


