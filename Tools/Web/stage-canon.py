#!/usr/bin/env python3
"""Stage both current Canon Art Web players after fresh tests and Root review.

This prepares a regular Artifacts directory for the existing publisher and
complete public HTTPS verifier. It never builds, publishes or reuses historical
game validation as a current pass.
"""
from datetime import datetime, timezone
from pathlib import Path
import argparse
import importlib.util
import json
import os
import shutil
import subprocess
import sys

from release_contract import contract, manifest_contract

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'Tools/Validation'))
from canon_release_evidence import (
    OUT, BUILD, REVISIONS, require, digest, runtime, verify_builds, verify_browser,
)
from LivingRpgClassic import profile as RELEASE

SPEC = importlib.util.spec_from_file_location('canon_stage_public_safety', ROOT / 'Tools/Web/stage-luminous.py')
SAFETY = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SAFETY)
GAMES = {'FantasyCards': 'fantasy-cards', 'PathOfDawn': 'path-of-dawn'}
MARKER = 'Generated by Tools/Web/' + ('stage-living-classic.py' if RELEASE.IS_LIVING else 'stage-canon.py') + '\n'
BUDGET = 985_000_000


