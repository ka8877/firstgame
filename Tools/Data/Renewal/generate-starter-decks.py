#!/usr/bin/env python3
import json,collections
from pathlib import Path
ROOT=Path(__file__).resolve().parents[3];HERE=Path(__file__).resolve().parent
cards=json.loads((ROOT/'Tools/Data/ClassicCards/selection.json').read_text())['cards'];q=lambda s:json.dumps(s,ensure_ascii=False)
E={1:('darkness','암흑','serin'),2:('fire','불','kael'),3:('water','물','serin'),4:('forest','숲','lyria'),5:('metal','금속','kael'),6:('earth','대지','noa'),7:('light','빛','noa')};result=[]
for e,(slug,name,leader)in E.items():
 pool=[c for c in cards if c['fields']['SoulType']==e];deck=[];count=collections.Counter()
 def add(c,n):
  n=min(n,c['fields']['DeckLimit']-count[c['sourceId']]);deck.extend(['fm_'+c['sourceId']]*n);count[c['sourceId']]+=n
 def fill(pool,n,copies=2):
  target=len(deck)+n
  for c in pool:
   if len(deck)==target:break
   add(c,min(copies,target-len(deck)))
  assert len(deck)==target,(slug,n,len(deck),target)
 for c in [c for c in pool if c['fields']['Category']==1][:4]:add(c,4)
 assert len(deck)==16
 units=[c for c in pool if c['fields']['Category']==2]
 fill(sorted([c for c in units if c['fields']['LV']<=2],key=lambda c:(not c['effect'].get('sourceSkillCode'),c['fields']['LV'],c['sourceId'])),12)
 fill(sorted([c for c in units if 3<=c['fields']['LV']<=4],key=lambda c:(c['fields']['RareType']not in(5,7),not c['effect'].get('sourceSkillCode'),c['fields']['LV'])),8)
 fill(sorted([c for c in units if c['fields']['RareType']in(7,5,4)],key=lambda c:(c['fields']['RareType']!=7,c['fields']['LV'],c['sourceId'])),4)
 fill([c for c in pool if c['fields']['Category']==3],6,4)
 for code in(str(15100741649+e-1),str(15112541671+e-1)):add(next(c for c in pool if c['sourceId']==code),1)
 fill(sorted([c for c in pool if c['fields']['Category']==4 and c['fields']['RareType']!=11],key=lambda c:(c['fields']['RareType']!=9,c['fields']['LV'])),2)
 assert len(deck)==50 and len(set(deck))>20
 result.append({'id':'renewal-'+slug,'name':name+'의 유산 · 기술과 시크릿','description':'원본 기술 유닛과 더블체인·이드카피 시크릿 장비를 사용하는 새 50장 연습 덱.','leader':leader,'cards':deck})
lines=['// Generated by Tools/Data/Renewal/generate-starter-decks.py.','namespace FantasyCards.Core','{',' internal static class RenewalStarterDeckData',' {','  internal static StarterDeckDefinition[] Create() => new StarterDeckDefinition[]','  {']
for d in result:lines.append('   new StarterDeckDefinition('+', '.join(q(d[k])for k in('id','name','description','leader'))+', '+', '.join(q(i)for i in d['cards'])+'),')
lines+=['  };',' }','}'];(ROOT/'Games/FantasyCards/Assets/Game/Core/RenewalStarterDeckData.cs').write_text('\n'.join(lines)+'\n');(HERE/'starter-decks.json').write_text(json.dumps({'decks':result},ensure_ascii=False,indent=2)+'\n');print('Added',len(result),'decks; preserved prior20.')
