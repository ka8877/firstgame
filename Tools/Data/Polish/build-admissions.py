#!/usr/bin/env python3
"""Explicit, source-preserving admission of complete premium techniques."""
import hashlib
import importlib.util
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
spec = importlib.util.spec_from_file_location('renewal', HERE.parent / 'Renewal/build-catalog.py')
renewal = importlib.util.module_from_spec(spec)
spec.loader.exec_module(renewal)
rows = {r['fields']['ID']: r['fields'] for r in json.loads((HERE.parent / 'Renewal/complete-observations.json').read_text())['cards']}
baseline = {r['sourceId'] for r in json.loads((HERE / 'compatibility-baseline-2571.json').read_text())['cards']}
attack = json.loads((HERE / 'attack-admissions.json').read_text())
admitted = {c['sourceId']: c for c in attack['safeAttackCards']}


def add(ids, **flags):
    for id in ids.split():
        assert id not in baseline
        f = rows[id]
        assert renewal.common(f) and f['Category'] == 2
        assert all(f.get(k) == 1 for k in ('ATKStatType', 'DEFStatType', 'HPStatType'))
        assert f['RareType'] in (4, 5, 7, 9, 11, 12)
        admitted[id] = {'sourceId': id, 'name': f['Name'], 'rarityCode': f['RareType'], 'effect': {
            'sourceSkillCode': f['Skill1'],
            'description': renewal.clean(f.get('TextExtra')),
            'premiumImplementation': 'BattleEngine.Polish.cs',
            'lateManual': 'Tools/Research/FmRenewal/faq736-text.txt',
            **flags,
        }}


# Seven source variants, all actual coin-defense with no extra status or aura.
add('10070724960 10070724968 10070724975 10070724982 10070724988 10070724997 10070725004', sourceDefenseSkillCode=662)
# Six Secret variants have precisely the same discard-to-hand rule. The dark
# seventh variant has an additional unsupported rule and is not silently added.
add('15100728142 15100728143 15100728144 15100728145 15100728146 15100728147')
add('3022820396 3061320558 3041120436 4021320946 9070124178')
# Exact existing techniques on previously excluded Rare variants.
add('13110627110 13110627111 13110627115')
add('10050424848 15050627918 15050627919 15050627920 15050627921 15051327932 9060324063', sourceDefenseSkillCode=18)
add('13100227071', sourceDefenseSkillCode=166)
# Third-upgrade printed ability is fully represented by capabilityMask=7 and
# the pre-existing strictly-below-level free equipment action.
add('11101925989 11101925990 11101925991 11101925992 11101925993 11101925994 11101925995 15010727788 15010727783 15010727789 13090427047', freeEquipmentBelowLevel=True)
# Second-upgrade production is applied at the actual soul-cost refresh, not
# represented by inventing a bonus to their printed combat values.
add('10022424695 10022424696 10022424699 10022424700 12110726451 12110726454 12110726456', upgradeProduction=True)
add('12110726455', sourceDefenseSkillCode=18, upgradeProduction=True)

ordered = sorted(admitted.values(), key=lambda c: (-rows[c['sourceId']]['ReleaseDate'], c['sourceId']))
for c in ordered:
    f = rows[c['sourceId']]
    assert c['sourceId'] not in baseline and c['name'] == f['Name']
    assert c['effect']['description'] == renewal.clean(f.get('TextExtra'))
    assert c['effect']['sourceSkillCode'] == f['Skill1']
    if f['Skill2'] != 1: assert c['effect'].get('sourceDefenseSkillCode') == f['Skill2']
    if c['effect'].get('freeEquipmentBelowLevel'): assert f['UnitType'] == 1
    c['sourceFieldsSha256'] = hashlib.sha256(json.dumps(f, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode()).hexdigest()

result = {'revision': 'fm-polish-2026-10-29', 'count': len(ordered), 'cards': ordered,
          'scope': 'Explicit complete premium abilities; original metadata, stats, art and IDs retained. Unsupported aura/status/fixed-symbol/hero rules remain view-only.'}
(HERE / 'premium-admissions.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')

lines = ['// Generated by Tools/Data/Polish/build-admissions.py.', 'namespace FantasyCards.Core', '{', ' public static class PolishCardSkills', ' {', '  public static int DefenseCode(string id)', '  {', '   switch(id)', '   {']
for c in ordered:
    if c['effect'].get('sourceDefenseSkillCode'):
        lines.append('    case "fm_' + c['sourceId'] + '": return ' + str(c['effect']['sourceDefenseSkillCode']) + ';')
lines += ['    default: return 0;', '   }', '  }', '  public static bool UpgradeProduction(string id)', '  {', '   switch(id)', '   {']
for c in ordered:
    if c['effect'].get('upgradeProduction'): lines.append('    case "fm_' + c['sourceId'] + '": return true;')
lines += ['    default: return false;', '   }', '  }', ' }', '}']
(ROOT / 'Games/FantasyCards/Assets/Game/Core/PolishCardSkills.cs').write_text('\n'.join(lines) + '\n')
print('Explicit premium additions:', len(ordered))
