#!/usr/bin/env python3
"""Generate engine definitions from the reviewed original-card observations. No network or image edits."""
from pathlib import Path
import collections,hashlib,json,re
ROOT=Path(__file__).resolve().parents[3]
SOURCE=ROOT/'Tools/Data/ClassicCards/selection.json'
OUTPUT=ROOT/'Games/FantasyCards/Assets/Game/Core/ClassicCardData.cs'
data=json.loads(SOURCE.read_text());cards=data['cards']
assert len(cards)==data['expectedCount'] and len({c['sourceId'] for c in cards})==len(cards)
assert {str(k):v for k,v in collections.Counter(c['fields']['Category'] for c in cards).items()}==data['counts']
E={1:'Darkness',2:'Fire',3:'Tide',4:'Forest',5:'Metal',6:'Earth',7:'Dawn'}
MASK={1:7,11:1,12:3,13:5,21:2,31:4,32:6}
K={1:'Terrain',2:'Unit',3:'Spell',4:'Equipment'}
COIN={1:'None',2:'Add',3:'Subtract',4:'Multiply',5:'Set'}
R=['Free','Common','Uncommon','Rare','Special','Upgrade','Unique','Event','Legend','Icajen','Secret','Epic']
def q(text):return json.dumps(str(text),ensure_ascii=False)
def souls(text):
 assert len(text)%4==0,text
 return [(int(text[i:i+2]),int(text[i+2:i+4])) for i in range(0,len(text),4) if int(text[i:i+2])!=1]
def coin(f,prefix):
 token=f.get(prefix+'Coin') or 'NONE';count=f.get(prefix+'CoinCount') or 0;kind=f.get(prefix+'CoinType') or 1
 if token=='NONE': assert count==0;return 'new CoinRule()'
 m=re.fullmatch(r'(\d*)C([1-5])',token);assert m,(f['Name'],token)
 assert count==int(m[2]);mult=int(m[1] or 1)
 return f'new CoinRule(CoinOperation.{COIN[kind]}, {count}, {mult})'
def operation(op):
 side={'ally':'Ally','enemy':'Enemy','both':'Both'}[op['side']]
 stat='PhysicalDamage' if op.get('kind')=='physicalDamage' else {'ap':'Attack','dp':'Defense','hp':'Health'}[op['stat']]
 delta=op.get('delta',op.get('amount',0))
 source={'ownCurrentDp':'OwnDefense','oneBasedSlot':'OneBasedSlot','negativeOneBasedSlot':'NegativeOneBasedSlot','negativeTotalEmptyFrontSlots':'NegativeEmptySlots'}.get(op.get('deltaSource'),'Constant')
 mask=sum(1<<(s-1) for s in op.get('slots',[1,2,3,4,5]));trait={'beast':1,'gear':2,'magic':4}.get(op.get('requiredTrait'),0)
 element='(int)Element.'+E[op['requiredSoulType']] if 'requiredSoulType' in op else '-1'
 return f'new SpellOperation {{ side = OperationSide.{side}, stat = OperationStat.{stat}, deltaSource = DeltaSource.{source}, delta = {delta}, laneMask = {mask}, requiredCapabilityMask = {trait}, requiredElement = {element} }}'
baseline=json.loads((SOURCE.parent/'compatibility-baseline-96.json').read_text())
starter_ids=['fm_'+c['sourceId'] for c in baseline['cards']]
assert len(starter_ids)==96 and set(starter_ids).issubset({'fm_'+c['sourceId'] for c in cards})
lines=['// Generated by Tools/Data/ClassicCards/generate-catalog.py; edit the reviewed selection, not this file.','namespace FantasyCards.Core','{','    internal static class ClassicCardData','    {','        // Preset decks retain their original source pool when the catalog grows.','        internal static readonly string[] StarterCardIds = new string[]','        {','            '+', '.join(q(i) for i in starter_ids),'        };','        internal static CardDefinition[] Create()','        {','            return new CardDefinition[]','            {']
for c in cards:
 f=c['fields'];cat=f['Category'];e=E[f['SoulType']];costs=souls(f['RequireSoul']);generic=sum(n for k,n in costs if k==81);color=sum(n for k,n in costs if k!=81)
 assert all(k==81 or k//10==f['SoulType'] for k,n in costs),(c['name'],costs)
 attack=f.get('ATK') or 0;defense=f.get('DEF') or 0;hp=f.get('HP') or 0
 effect=c.get('effect',{});text=effect.get('description','')
 if cat==4:
  assert f['Skill1']==f['Skill2']==1
  for stat,key in [('ATK','attackDelta'),('DEF','defenseDelta'),('HP','healthDelta')]:
   kind=f.get(stat+'StatType',1);assert kind in (1,31,32),(c['name'],stat,kind)
   assert effect[key]==(0 if kind==1 else f[stat]*(1 if kind==31 else -1)),(c['name'],stat)
  attack=effect['attackDelta'];defense=effect['defenseDelta'];hp=effect['healthDelta']
  text=f'AP {attack:+d} · DP {defense:+d} · HP {hp:+d}'
 elif cat==2:text=effect.get('description','특수 기술 없음. 전투에서 카드의 AP·DP·HP 코인을 함께 판정합니다.')
 elif cat==1:text='LP로 전개하고 소울 코스트 단계마다 소울을 회복합니다.'
 line=f'                new CardDefinition({q("fm_"+c["sourceId"])}, {q(c["name"])}, {q(text)}, CardKind.{K[cat]}, Element.{e}, {color+generic}, attack: {attack}, health: {hp}, coinBonus: 0, rarity: CardRarity.{R[f["RareType"]-1]}, level: {f["LV"]}, coloredCost: {color}, genericCost: {generic}, defense: {defense})'
 lines.append(line);props=[f'sourceId = {q(c["sourceId"])}',f'sourceUrl = {q(c["sourceUrl"])}',f'artResource = {q(c["artResource"])}',f'deckLimit = {f["DeckLimit"]}']
 if cat==1:
  produced=souls(f['EarnSoulList']);assert all(k==81 or k//10==f['SoulType'] for k,n in produced)
  props.extend([f'landPointCost = {f["RequireLP"]}',f'producedColored = {sum(n for k,n in produced if k!=81)}',f'producedGeneric = {sum(n for k,n in produced if k==81)}'])
 if cat==2:
  assert f['Skill1']==f['Skill2']==1 and f['ATKStatType']==f['DEFStatType']==f['HPStatType']==1
  rank={1:'N',2:'C',3:'B',4:'A',5:'S'}[f.get('RankType',1)]
  props.extend([f'rank = CardRank.{rank}',f'capabilityMask = {MASK[f["UnitType"]]}',f'attackCoin = {coin(f,"ATK")}',f'defenseCoin = {coin(f,"DEF")}',f'healthCoin = {coin(f,"HP")}'])
  if effect.get('freeEquipmentBelowLevel'):props.append('freeEquipmentBelowLevel = true')
  if effect.get('discardGenericSoul'):props.append(f'discardGenericSoul = {effect["discardGenericSoul"]}')
 else:props.extend(['attackCoin = new CoinRule()','defenseCoin = new CoinRule()','healthCoin = new CoinRule()'])
 if cat==4:
  props.append(f'requiredCapabilityMask = {0 if f["UnitType"]==1 else MASK[f["UnitType"]]}')
 if cat==3:
  assert f['Duration']==1 and f['DurationType']==1
  props.extend(['effect = Effect.StatOperations',f'playWindow = PlayWindow.{{1}}'.replace('{1}',{1:'Any',2:'AttackOnly',3:'DefenseOnly'}[f['TurnType']]),'operations = new SpellOperation[] { '+', '.join(operation(op) for op in effect['operations'])+' }'])
 lines.append('                { '+', '.join(props)+' },')
lines.extend(['            };','        }','    }','}'])
OUTPUT.write_text('\n'.join(lines)+'\n')
print(f'Generated {len(cards)} original definitions: {OUTPUT.relative_to(ROOT)}')
print('Selection SHA256:',hashlib.sha256(SOURCE.read_bytes()).hexdigest())
