"""Sharp-only immutable source-gallery aliases for a fresh generated stage.

Importing performs no validation or mutation. The caller must first complete
the ordinary build/media/browser gates. This module never publishes, replaces
a source/target image, cleans up a partial run, or grants visual approval.
"""
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import stat

ROOT = Path(__file__).resolve().parents[3]
FOLDER = ROOT / 'Tools/Validation/SharpIllustration'
SOURCE = FOLDER / 'stage_gallery_storage.py'
MEDIA = ROOT / 'Tools/Data/Renewal/media-manifest.json'
ASSETS = ROOT / 'Games/FantasyCards/Assets'
COUNT = 15350
REVISION = 'fm-sharp-client-2026-11-17'
NAME = re.compile(r'StreamingAssets/Cards/fm_([0-9]+)\.jpg')
SHA = re.compile(r'[0-9a-f]{64}')
MARKER = 'Generated by Tools/Web/stage-sharp-illustration.py\n'
LEDGER_NAME = 'generated-stage-gallery-storage.json'


def _need(condition, message):
    if not condition:
        raise ValueError(message)


def _now():
    return datetime.now(timezone.utc).isoformat()


def _regular(path, directory=False):
    path = Path(path)
    _need(path.is_absolute() and path.absolute() == path
          and not any(part in ('.', '..') for part in path.parts)
          and not any(item.is_symlink() for item in (path, *path.parents)),
          'An absolute canonical path without symlinks is required: ' + str(path))
    value = path.lstat()
    _need(stat.S_ISDIR(value.st_mode) if directory else stat.S_ISREG(value.st_mode),
          'A regular gallery file/directory is required: ' + str(path))
    return path


def _attrs(path):
    value = _regular(path).lstat()
    return {'dev': value.st_dev, 'ino': value.st_ino, 'bytes': value.st_size,
            'mode': stat.S_IMODE(value.st_mode), 'uid': value.st_uid,
            'gid': value.st_gid, 'mtimeNs': value.st_mtime_ns,
            'ctimeNs': value.st_ctime_ns, 'blocks': value.st_blocks,
            'nlink': value.st_nlink}


def _sha(path):
    value = hashlib.sha256()
    with _regular(path).open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            value.update(block)
    return value.hexdigest()


def _ref(path):
    path = _regular(path)
    before = _attrs(path)
    result = {'file': path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT)
              else str(path), 'bytes': before['bytes'], 'sha256': _sha(path)}
    _need(_attrs(path) == before, 'Input changed while reading: ' + str(path))
    return result


def _bound(path, reference):
    _need(isinstance(reference, dict) and _ref(path) == reference,
          'Exact current declared input reference required: ' + str(path))


def _same_original(actual, before, added):
    return (all(actual[key] == before[key] for key in before
                if key not in ('nlink', 'ctimeNs'))
            and actual['nlink'] == before['nlink'] + added
            and actual['ctimeNs'] >= before['ctimeNs']
            and (added != 0 or actual['ctimeNs'] == before['ctimeNs']))


def _row(row):
    _need(isinstance(row, dict) and isinstance(row.get('file'), str)
          and type(row.get('bytes')) is int and row['bytes'] >= 0
          and isinstance(row.get('sha256'), str) and SHA.fullmatch(row['sha256']),
          'Explicit nonnegative byte count and SHA256 runtime/source row required')
    return {'file': row['file'], 'bytes': row['bytes'], 'sha256': row['sha256']}


def _rows(rows):
    _need(isinstance(rows, list), 'An exact list of current source/runtime rows is required')
    values = [_row(row) for row in rows]
    _need(len(values) == len({row['file'] for row in values}), 'Duplicate source/runtime names are forbidden')
    return {row['file']: row for row in values}


def _metadata_unchanged(state):
    for value in state['metadata']:
        _need(_ref(Path(value['path'])) == value['reference']
              and _attrs(Path(value['path'])) == value['attributes'],
              'Bound gallery manifest/proof/build metadata changed: ' + value['path'])


def _ledger(state, status, error=None):
    result = {'schema': 1, 'releaseProfile': 'sharp-illustration', 'status': status,
        'scope': 'Fresh stage gallery aliases only; every retained source inode/content/mode/mtime remains immutable. No test, publication or visual approval is granted.',
        'artifactPath': str(state['stage']), 'actualRoot': str(state['stage']),
        'ownershipMarker': MARKER, 'preparedUtc': state['preparedUtc'],
        'revision': REVISION, 'sourceFingerprint': state['sourceFingerprint'],
        'buildRoot': str(state['build']), 'proofRoot': str(state['proof']),
        'expectedCount': COUNT, 'linkedCount': state['linkedCount'],
        'logicalGalleryBytes': state['logicalBytes'], 'metadata': state['metadata'],
        'aliasRule': 'All source and stage aliases are immutable, including content/chmod/utime; only creation of these new targets and the resulting original nlink/ctime changes are authorized.',
        'sourceGroups': list(state['groups'].values()), 'files': list(state['entries'].values())}
    if status != 'prepared-before-any-gallery-link':
        result['finishedUtc'] = _now()
    if error is not None:
        result['failure'] = str(error)
        result['partialAliasesPreserved'] = True
    return result


def _write_final(state, status, error=None):
    # Exactly one final full JSON write, in addition to the initial full plan.
    # The final record retains every source-before row and all actual progress.
    _need(state['phase'] == 'prepared', 'Gallery attempt is terminal; preserve it and use a fresh stage')
    _need(_ref(state['ledger']) == state['initialLedger'], 'Prepared gallery plan changed during linking')
    temporary = state['ledger'].with_name(state['ledger'].name + '.finalizing')
    with temporary.open('x', encoding='utf-8') as stream:
        json.dump(_ledger(state, status, error), stream, indent=2)
        stream.write('\n')
        stream.flush()
        os.fsync(stream.fileno())
    os.replace(temporary, state['ledger'])
    state['phase'] = 'completed' if error is None else 'failed'
    return _ref(state['ledger'])


def _failed(state, error):
    if state['phase'] == 'prepared':
        try:
            _write_final(state, 'failed-partial-aliases-preserved', error)
        finally:
            state['phase'] = 'failed'


def prepare_gallery(build_root, proof_root, declared_build, stage, ledger_path):
    """Validate all 15,350 source/build pairs, then persist intent before linking.

    Returns opaque state. Targets are not created here. Existing source aliases
    are accepted and grouped by device/inode; every new target adds exactly one
    link to its observed source group. The caller owns its fresh stage/ledger.
    """
    _need(os.environ.get('FIRSTGAME_RELEASE_PROFILE') == 'sharp-illustration',
          'Gallery source sharing is exclusive to the explicit Sharp profile')
    _need(Path(__file__).resolve() == SOURCE, 'Only the captured canonical gallery module may execute')
    expected_build = Path(os.environ.get('FIRSTGAME_BUILD_ROOT', '/tmp/firstgame-sharp-illustration-20261117-builds')) / 'FantasyCards/Web'
    expected_proof = Path(os.environ.get('FIRSTGAME_PROOF_ROOT', str(ROOT / 'Artifacts/Validation/Autonomy/SharpIllustration-2026-11-17/BuildProof'))) / 'FantasyCards-Web'
    expected_out = Path(os.environ.get('FIRSTGAME_VALIDATION_ROOT', str(ROOT / 'Artifacts/Validation/SharpIllustration-2026-11-17')))
    build, proof, stage, ledger = map(Path, (build_root, proof_root, stage, ledger_path))
    _need(build == expected_build and proof == expected_proof,
          'Only the exact current build and retained proof may supply gallery identity')
    _regular(build, True); _regular(proof, True); _regular(stage, True); _regular(expected_out, True)
    _need(proof.is_relative_to(ROOT / 'Artifacts/Validation/Autonomy')
          and expected_out.is_relative_to(ROOT / 'Artifacts/Validation')
          and stage != ROOT / 'Artifacts' and stage.is_relative_to(ROOT / 'Artifacts')
          and not stage.is_relative_to(expected_out) and not expected_out.is_relative_to(stage)
          and not stage.is_relative_to(proof) and not proof.is_relative_to(stage)
          and not stage.is_relative_to(build) and not build.is_relative_to(stage)
          and ledger == expected_out / LEDGER_NAME and not os.path.lexists(ledger)
          and not os.path.lexists(ledger.with_name(ledger.name + '.finalizing')),
          'Fresh separate owned stage/gallery ledger under current output is required')
    marker = _regular(stage / '.firstgame-web-output')
    _need(marker.read_text() == MARKER, 'Fresh Sharp generated-stage ownership marker required')
    destination = stage / 'games/fantasy-cards/StreamingAssets/Cards'
    _need(not os.path.lexists(destination)
          or (_regular(destination, True) and not any(destination.iterdir())),
          'Gallery targets must all be absent in the fresh stage')

    _need(isinstance(declared_build, dict), 'Actual verified current build declaration required')
    index_path = proof / 'build-proof-index.json'
    _bound(index_path, declared_build.get('proof'))
    _bound(build / 'BuildInputs.json', declared_build.get('inputs'))
    _bound(build / 'BuildEvidence.txt', declared_build.get('evidence'))
    metadata_paths = (SOURCE, MEDIA, index_path, build / 'BuildInputs.json', build / 'BuildEvidence.txt',
                      proof / 'BuildInputs.json', proof / 'BuildEvidence.txt', marker)
    metadata = [{'path': str(path), 'reference': _ref(path), 'attributes': _attrs(path)} for path in metadata_paths]
    # Bind the snapshots above to the caller's actual verified references too;
    # their bytes must remain the same across all parsing and image checks.
    for path, key in ((index_path, 'proof'), (build / 'BuildInputs.json', 'inputs'),
                      (build / 'BuildEvidence.txt', 'evidence')):
        captured = next(value['reference'] for value in metadata if value['path'] == str(path))
        _need(captured == declared_build.get(key), 'Gallery metadata snapshot differs from the verified declaration')
    index = json.loads(index_path.read_bytes())
    inputs = json.loads((build / 'BuildInputs.json').read_bytes())
    fingerprint = declared_build.get('native', {}).get('sourceFingerprint')
    _need(isinstance(fingerprint, str) and SHA.fullmatch(fingerprint)
          and index.get('schema') == 1 and index.get('status') == 'preserved'
          and index.get('game') == inputs.get('game') == 'FantasyCards'
          and index.get('revision') == REVISION and index.get('target') == 'WebGL'
          and index.get('reportedBuildExitCode') == 0
          and index.get('sourceFingerprint') == inputs.get('fingerprint') == fingerprint
          and index.get('originalBuildFolder') == str(build)
          and index.get('runtimeByteIdentityBeforeAfter') is True
          and index.get('coreRuntimeBytesCopied') is True,
          'Exact successful current source/build/proof binding required')
    copies = _rows(index.get('copiedOriginals'))
    for name in ('BuildInputs.json', 'BuildEvidence.txt'):
        current = _ref(build / name)
        _need(copies.get(name) == {'file': name, 'bytes': current['bytes'], 'sha256': current['sha256']}
              and _sha(proof / name) == current['sha256']
              and _attrs(proof / name)['bytes'] == current['bytes'],
              'Current metadata must match its unchanged independently retained original')
    runtime = _rows(index.get('completeRuntimeFiles'))
    sources = _rows(inputs.get('files'))
    _need(inputs['fingerprint'] == hashlib.sha256(''.join(row['file'] + '\0' + str(row['bytes']) + '\0' + row['sha256'] + '\n'
          for row in inputs['files']).encode()).hexdigest(), 'Build source rows must match their exact recorded fingerprint')
    manifest = json.loads(_regular(MEDIA).read_bytes())
    _need(all(manifest.get(key) == COUNT for key in ('sourceCount', 'count', 'available', 'materialized'))
          and manifest.get('missing') == 0 and manifest.get('completeTraversal') is True
          and manifest.get('cacheInventoryComplete') is True
          and isinstance(manifest.get('cards'), list) and len(manifest['cards']) == COUNT,
          'Complete available source-gallery metadata required; partial inventories are forbidden')
    expected = {}
    for card in manifest['cards']:
        identity = card.get('sourceId')
        _need(isinstance(identity, str) and re.fullmatch(r'[0-9]+', identity), 'Numeric original source identity required')
        name = 'StreamingAssets/Cards/fm_' + identity + '.jpg'
        source_name = 'Games/FantasyCards/Assets/' + name
        row = _row({'file': name, 'bytes': card.get('deliveryBytes'), 'sha256': card.get('deliverySha256')})
        _need(name not in expected and row['bytes'] > 0 and card.get('delivery') == source_name
              and card.get('status') == 'available' and card.get('materialized') is True
              and card.get('fullFrame') is True and card.get('jpegQuality') == 88
              and card.get('jpegSubsampling') == 2
              and runtime.get(name) == row
              and sources.get(source_name) == {**row, 'file': source_name},
              'Every exact source ID must bind retained media, current input and complete runtime bytes')
        expected[name] = row
    _need(len(expected) == COUNT
          and {name for name in runtime if name.startswith('StreamingAssets/Cards/')} == set(expected)
          and sum(row['bytes'] for row in expected.values()) == manifest.get('deliveryBytes'),
          'Exact full gallery name/count/byte set required; no extra runtime gallery entries')
    gallery = _regular(build / 'StreamingAssets/Cards', True)
    source_gallery = _regular(ASSETS / 'StreamingAssets/Cards', True)
    basenames = {Path(name).name for name in expected}
    _need({path.name for path in gallery.iterdir()} == basenames
          and {path.name for path in source_gallery.glob('*.jpg')} == basenames,
          'Current source/build JPEG inventory must equal the complete declared gallery')

    entries, groups = {}, {}
    for name, row in sorted(expected.items()):
        source, build_path = ASSETS / name, build / name
        before, build_before = _attrs(source), _attrs(build_path)
        _need(before['nlink'] >= 1 and before['dev'] == stage.stat().st_dev
              and before['bytes'] == build_before['bytes'] == row['bytes'],
              'Every retained source and new stage must use the same filesystem and exact length')
        key = str(before['dev']) + ':' + str(before['ino'])
        if key not in groups:
            _need(_sha(source) == row['sha256'] and _attrs(source) == before,
                  'Actual retained source gallery bytes/attributes differ: ' + name)
            groups[key] = {'group': key, 'sourceBefore': before, 'sourceNames': [],
                           'expectedSha256': row['sha256'], 'linkedCount': 0}
        group = groups[key]
        _need(group['sourceBefore'] == before and group['expectedSha256'] == row['sha256']
              and _sha(build_path) == row['sha256'] and _attrs(build_path) == build_before,
              'Source inode aliases or actual current build bytes disagree: ' + name)
        group['sourceNames'].append(name)
        entries[name] = {'name': name, 'source': str(source), 'build': str(build_path),
            'target': str(stage / 'games/fantasy-cards' / name), 'expected': row,
            'sourceGroup': key, 'sourceBefore': before, 'buildBefore': build_before,
            'status': 'planned-target-absent'}
    state = {'build': build, 'proof': proof, 'stage': stage, 'ledger': ledger,
        'sourceFingerprint': fingerprint, 'preparedUtc': _now(), 'metadata': metadata,
        'logicalBytes': manifest['deliveryBytes'], 'entries': entries, 'groups': groups,
        'linkedCount': 0, 'phase': 'prepared'}
    _metadata_unchanged(state)
    with ledger.open('x', encoding='utf-8') as stream:
        json.dump(_ledger(state, 'prepared-before-any-gallery-link'), stream, indent=2)
        stream.write('\n'); stream.flush(); os.fsync(stream.fileno())
    state['initialLedger'] = _ref(ledger)
    return state


def link_gallery(state, name, target):
    """Create exactly one new alias; any failure preserves this whole attempt."""
    _need(state['phase'] == 'prepared', 'Gallery attempt is terminal; no retries or cleanup')
    try:
        _need(isinstance(name, str) and NAME.fullmatch(name) and name in state['entries'],
              'Only an exact planned original-gallery basename is linkable')
        entry = state['entries'][name]
        source, target = Path(entry['source']), Path(target)
        group = state['groups'][entry['sourceGroup']]
        before = _attrs(source)
        _need(entry['status'] == 'planned-target-absent' and target == Path(entry['target'])
              and not os.path.lexists(target) and _regular(target.parent, True)
              and before['dev'] == target.parent.stat().st_dev
              and _same_original(before, group['sourceBefore'], group['linkedCount'])
              and _sha(source) == entry['expected']['sha256'] and _attrs(source) == before,
              'Exact unchanged source and absent same-filesystem stage target required')
        entry['status'] = 'intent-before-new-link'
        os.link(source, target, follow_symlinks=False)
        # Count immediately so a subsequent failed verification records the
        # alias that was actually created, never deletes it, and never retries.
        state['linkedCount'] += 1; group['linkedCount'] += 1
        entry['status'] = 'linked-awaiting-byte-verification'
        after, target_after = _attrs(source), _attrs(target)
        _need(after == target_after
              and _same_original(after, group['sourceBefore'], group['linkedCount'])
              and _sha(target) == entry['expected']['sha256']
              and _attrs(source) == after == _attrs(target),
              'Only original source nlink/ctime may change when creating its verified new alias')
        entry.update(status='verified-linked-original-retained', sourceAfter=after, targetAfter=target_after)
        group['sourceAfter'] = after
    except Exception as error:
        _failed(state, error)
        raise


def finish_gallery(state):
    """Recheck every source/build/alias byte and group, then return the ledger ref."""
    _need(state['phase'] == 'prepared', 'Gallery attempt is terminal; preserve partial aliases')
    try:
        _need(state['linkedCount'] == len(state['entries']) == COUNT,
              'Every one of the 15,350 intended fresh gallery aliases must exist')
        _metadata_unchanged(state)
        actual = _regular(state['stage'] / 'games/fantasy-cards/StreamingAssets/Cards', True)
        _need({path.name for path in actual.iterdir()} == {Path(name).name for name in state['entries']},
              'Final staged gallery must have exactly the admitted targets')
        for entry in state['entries'].values():
            source, build, target = map(Path, (entry['source'], entry['build'], entry['target']))
            group = state['groups'][entry['sourceGroup']]
            after, build_after, target_after = _attrs(source), _attrs(build), _attrs(target)
            build_key = str(build_after['dev']) + ':' + str(build_after['ino'])
            allowed_build = state['groups'].get(build_key)
            _need(entry['status'] == 'verified-linked-original-retained'
                  and after == target_after
                  and _same_original(after, group['sourceBefore'], group['linkedCount'])
                  and group['linkedCount'] == len(group['sourceNames'])
                  and (_same_original(build_after, entry['buildBefore'], allowed_build['linkedCount'])
                       if allowed_build else build_after == entry['buildBefore'])
                  and _sha(source) == _sha(build) == _sha(target) == entry['expected']['sha256']
                  and _attrs(source) == after == _attrs(target) and _attrs(build) == build_after,
                  'Final complete gallery byte/inode/attribute identity failed: ' + entry['name'])
            entry.update(sourceAfter=after, targetAfter=target_after, buildAfter=build_after)
            group['sourceAfter'] = after
        _metadata_unchanged(state)
        return _write_final(state, 'all-15350-current-gallery-original-inodes-retained')
    except Exception as error:
        _failed(state, error)
        raise
