def need(value, message):
    if not value:
        raise ValueError(message)


def safe(value):
    path = Path(value)
    need(path.is_absolute() and '..' not in path.parts and path.absolute() == path
         and not any(item.is_symlink() for item in (path, *path.parents)), 'Exact regular path required: ' + str(path))
    return path


def regular(value):
    path = safe(value)
    need(stat.S_ISREG(path.lstat().st_mode), 'Regular original required: ' + str(path))
    return path


def attrs(path):
    value = regular(path).stat()
    return {'dev': value.st_dev, 'ino': value.st_ino, 'bytes': value.st_size,
            'mode': stat.S_IMODE(value.st_mode), 'mtimeNs': value.st_mtime_ns,
            'ctimeNs': value.st_ctime_ns, 'nlink': value.st_nlink}


def hashes(path):
    path = regular(path)
    before = attrs(path)
    sha, oid = hashlib.sha256(), hashlib.sha1()
    oid.update(('blob ' + str(before['bytes']) + '\0').encode('ascii'))
    with path.open('rb') as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b''):
            sha.update(block); oid.update(block)
    need(attrs(path) == before, 'Original changed during hashing: ' + str(path))
    return {'bytes': before['bytes'], 'sha256': sha.hexdigest(), 'gitBlob': oid.hexdigest()}


def ref(path):
    path = regular(path)
    row = hashes(path)
    return {'file': str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path),
            'bytes': row['bytes'], 'sha256': row['sha256']}


def read(path):
    return json.loads(regular(path).read_bytes())


def write(path, value):
    safe(path.parent)
    with path.open('x') as stream:
        json.dump(value, stream, ensure_ascii=False, indent=2)
        stream.write('\n'); stream.flush(); os.fsync(stream.fileno())


def checked(row):
    need(isinstance(row, dict) and isinstance(row.get('file'), str), 'Explicit original reference required')
    path = Path(row['file'])
    path = path if path.is_absolute() else ROOT / path
    need(ref(path) == row, 'Current original reference differs: ' + str(path))
    return path


def good(event):
    return (event.get('exitCode') == 0 and event.get('containmentProvedEmpty') is True
            and event.get('supervisorStillAlive') is False)


def stamp(value):
    result = datetime.fromisoformat(value.replace('Z', '+00:00'))
    need(result.utcoffset() is not None, 'Aware actual timestamp required')
    return result


def owned(label, requested):
    need(all(os.environ.get(key) == value for key, value in ENV.items()), 'Exact current Sharp environment required')
    raw = regular(CONTROL / 'lease.json').read_bytes()
    lease = json.loads(raw)
    need(lease.get('state') == 'acquired' and lease.get('lease', {}).get('runId') == CONTROL.name
         and isinstance(lease.get('commitSha'), str) and re.fullmatch(r'[0-9a-f]{40}', lease['commitSha'])
         and isinstance(lease['lease'].get('owner'), str), 'Actual acquired Sharp lease required')
    deadline = datetime.fromisoformat(lease['lease']['deadlineUtc'])
    need(deadline.utcoffset() is not None and (deadline - datetime.now(timezone.utc)).total_seconds() > 180,
         'Actual fixed lease budget exhausted')
    run = CONTROL / 'CommandRuns' / label
    invocation = read(run / 'invocation.json')
    need(invocation.get('requestedArgv') == requested and invocation.get('label') == label
         and invocation.get('scope') == 'generic-owned-command-only' and not (run / 'summary.json').exists(),
         'Exact live owned invocation required')
    need(regular(checked(invocation['ownedLeaseSnapshot'])).read_bytes() == raw, 'Executed current lease differs')
    idle = read(run / 'Processes/idleBefore.finished.json')
    need(good(idle) and idle.get('argv', [])[1:] == ['Tools/Environment/assert-runtime-idle.py'],
         'Completed independent idle receipt required')
    found, pid = False, os.getppid()
    for _ in range(64):
        if pid <= 1:
            break
        proc = Path('/proc') / str(pid)
        words = proc.joinpath('cmdline').read_bytes().decode(errors='replace').split('\0')
        found |= any(word == str(WRAPPER) and index + 1 < len(words) and words[index + 1] == label
                     for index, word in enumerate(words))
        pid = int(proc.joinpath('stat').read_text().split(') ', 1)[1].split()[1])
    need(found and ref(run / 'RecordedHarness' / Path(__file__).absolute().relative_to(ROOT))['sha256']
         == ref(Path(__file__).absolute())['sha256'], 'Actual wrapper ancestry/recorded source differs')
    return run, raw, deadline


