#!/usr/bin/env python3
"""Package exact current two-game players, full LFS sources and fresh evidence."""
from datetime import datetime,timezone
import argparse,importlib.util,json,shutil,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT/'Tools/Validation'))
from renewal_release_evidence import OUT,BUILD,REVISIONS,CURRENT_TARGETS,require,read,ref,digest,runtime,verify_builds,verify_browser,verify_portal_review
import chronicle_archive_storage as ARCHIVE_STORAGE
spec=importlib.util.spec_from_file_location('renewal_archive_base',ROOT/'Tools/Build/package-modern.py');BASE=importlib.util.module_from_spec(spec);spec.loader.exec_module(BASE)
DEST=Path('/tmp/firstgame-chronicle-deliverables');LINK=ROOT/'Artifacts/ChronicleDeliverables';STAGE=Path('/tmp/firstgame-chronicle-staged-site');MARKER='Generated by Tools/Build/package-renewal.py\n'
BASE.ART=DEST;BASE.EXCLUDED.update({'.pki','.cache','.local','.npm'})
GAMES={'FantasyCards':'fantasy-cards','PathOfDawn':'path-of-dawn'}

def previous(name):
 p=DEST/name
 require(not p.exists(),'Retain an existing current archive; do not rotate/repack it: '+str(p))
BASE.archive_previous=previous
BASE.verify=lambda archive,entries:ARCHIVE_STORAGE.verify_with_member_receipt(archive,entries,BASE.safe)

def shipping(p):
 if p.name=='settings.map' and 'MonoBleedingEdge' in p.parts:return True
 return BASE.shipping(p) and '.symbols.' not in p.name

def storage():
 if DEST.exists():require(DEST.is_dir() and not DEST.is_symlink() and (DEST/'.firstgame-renewal-deliverables').read_text()==MARKER,'Unexpected archive root')
 if LINK.exists() or LINK.is_symlink():require(LINK.is_symlink() and LINK.readlink()==DEST,'Unexpected artifact link')
 ledger=OUT/'generated-deliverables-storage.json';expected={'status':'prepared','artifactPath':str(LINK),'actualRoot':str(DEST)}
 if ledger.exists():require(all(read(ledger).get(k)==v for k,v in expected.items()),'Changed archive storage ledger')
 else:ledger.write_text(json.dumps({**expected,'preparedUtc':datetime.now(timezone.utc).isoformat()},indent=2)+'\n')
 DEST.mkdir(exist_ok=True);(DEST/'.firstgame-renewal-deliverables').write_text(MARKER)
 if not LINK.is_symlink():LINK.symlink_to(DEST,target_is_directory=True)

def inputs():
 builds=verify_builds()
 for game in GAMES:
  for profile in ('Desktop720','Mobile844','PublicMobile844'):verify_browser(game,profile)
 manifest=read(STAGE/'build-manifest.json');require(manifest.get('releaseProfile')=='renewal' and manifest.get('currentTargets')==list(CURRENT_TARGETS) and manifest.get('sourceDirty') is False and manifest.get('publishReady') is True and manifest.get('gameRevisions')==REVISIONS,'Current verified Web-only stage required')
 for name,h in manifest['files'].items():
  p=STAGE/name;require(p.resolve().is_relative_to(STAGE) and p.is_file() and digest(p)==h,'Staged bytes changed: '+name);BASE.safe(p)
 public=read(OUT/'PublicPortal/report.json');verify_portal_review(public)
 require(public['manifest']['sha256']==digest(STAGE/'build-manifest.json'),'Public and staged manifest differ')
 for game,slug in GAMES.items():
  built=runtime(BUILD/game/'Web');staged=runtime(STAGE/'games'/slug);require(set(built)==set(staged),'Published runtime set differs: '+game)
  for name,p in built.items():require(digest(p)==digest(staged[name]),'Published runtime byte changed: '+game+'/'+name)
 require(not subprocess.check_output(['git','status','--porcelain'],cwd=ROOT,text=True),'Commit final source and release metadata before packaging')
 return {'sourceCommit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'stagedSourceCommit':manifest['sourceCommit'],'stageManifest':ref(STAGE/'build-manifest.json'),'builds':builds,'public':ref(OUT/'PublicPortal/report.json')}

