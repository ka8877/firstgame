#!/usr/bin/env python3
"""Package exact current two-game players, full LFS sources and fresh evidence."""
from datetime import datetime,timezone
import argparse,importlib.util,json,shutil,subprocess,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2];sys.path.insert(0,str(ROOT/'Tools/Validation'))
from renewal_release_evidence import OUT,BUILD,REVISIONS,require,read,ref,digest,runtime,verify_builds,verify_browser,verify_portal_review
spec=importlib.util.spec_from_file_location('renewal_archive_base',ROOT/'Tools/Build/package-modern.py');BASE=importlib.util.module_from_spec(spec);spec.loader.exec_module(BASE)
DEST=Path('/tmp/firstgame-renewal-deliverables');LINK=ROOT/'Artifacts/RenewalDeliverables';STAGE=Path('/tmp/firstgame-renewal-staged-site');MARKER='Generated by Tools/Build/package-renewal.py\n'
BASE.ART=DEST;BASE.EXCLUDED.update({'.pki','.cache','.local','.npm'})
GAMES={'FantasyCards':'fantasy-cards','PathOfDawn':'path-of-dawn'}

def previous(name):
 p=DEST/name
 if p.exists():
  folder=DEST/'Previous';folder.mkdir(exist_ok=True);p.rename(folder/(p.stem+'-'+datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')+p.suffix))
BASE.archive_previous=previous

def shipping(p):
 if p.name=='settings.map' and 'MonoBleedingEdge' in p.parts:return True
 return BASE.shipping(p) and '.symbols.' not in p.name

def storage():
 if DEST.exists():require(DEST.is_dir() and not DEST.is_symlink() and (DEST/'.firstgame-renewal-deliverables').read_text()==MARKER,'Unexpected archive root')
 if LINK.exists() or LINK.is_symlink():require(LINK.is_symlink() and LINK.readlink()==DEST,'Unexpected artifact link')
 ledger=OUT/'generated-deliverables-storage.json';expected={'status':'prepared','artifactPath':str(LINK),'actualRoot':str(DEST)}
 if ledger.exists():require(all(read(ledger).get(k)==v for k,v in expected.items()),'Changed archive storage ledger')
 else:ledger.write_text(json.dumps({**expected,'preparedUtc':datetime.now(timezone.utc).isoformat()},indent=2)+'\n')
 DEST.mkdir(exist_ok=True);(DEST/'.firstgame-renewal-deliverables').write_text(MARKER)
 if not LINK.is_symlink():LINK.symlink_to(DEST,target_is_directory=True)

def inputs():
 builds=verify_builds()
 for game in GAMES:
  for profile in ('Desktop720','Mobile844','PublicMobile844'):verify_browser(game,profile)
 manifest=read(STAGE/'build-manifest.json');require(manifest.get('releaseProfile')=='renewal' and manifest.get('sourceDirty') is False and manifest.get('publishReady') is True and manifest.get('gameRevisions')==REVISIONS,'Current verified stage required')
 for name,h in manifest['files'].items():
  p=STAGE/name;require(p.resolve().is_relative_to(STAGE) and p.is_file() and digest(p)==h,'Staged bytes changed: '+name);BASE.safe(p)
 public=read(OUT/'PublicPortal/report.json');verify_portal_review(public)
 require(public['manifest']['sha256']==digest(STAGE/'build-manifest.json'),'Public and staged manifest differ')
 for game,slug in GAMES.items():
  built=runtime(BUILD/game/'Web');staged=runtime(STAGE/'games'/slug);require(set(built)==set(staged),'Published runtime set differs: '+game)
  for name,p in built.items():require(digest(p)==digest(staged[name]),'Published runtime byte changed: '+game+'/'+name)
 require(not subprocess.check_output(['git','status','--porcelain'],cwd=ROOT,text=True),'Commit final source and release metadata before packaging')
 return {'sourceCommit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=ROOT,text=True).strip(),'stagedSourceCommit':manifest['sourceCommit'],'stageManifest':ref(STAGE/'build-manifest.json'),'builds':builds,'public':ref(OUT/'PublicPortal/report.json')}

def notes(game,target):
 folder=BUILD/game/target
 launch=f'압축을 모두 풀고 {game}.exe를 실행하세요. 데이터 폴더와 DLL도 함께 필요합니다.' if target=='Windows' else '전체 폴더를 HTTP/HTTPS 서버로 실행하세요. file:// 직접 실행은 지원하지 않습니다.'
 text='카드 원본 도감과 실제 출전 가능한 카드는 구분됩니다. 미지원 기술이 있는 원본은 설명과 함께 도감에서 살펴보세요.\n게임 시작 → AI 방 → 덱 선택 → 대전 시작. 카드 클릭/드래그로 배치합니다.' if game=='FantasyCards' else '탄생 도입에서 열두 살 성전 여정으로 이어지는 첫 장입니다.\n새 15개 말씀 여정은 타이틀의 새 여정으로 시작하세요. 이전 저장의 이어하기는 기존 경로를 유지합니다.\nA/D 이동, Shift 달리기, Space 점프, E 대화, 휠 줌, I 인물, B 가방, M 말씀 도감, Esc 메뉴. 모바일은 화면 버튼을 사용합니다.'
 (folder/'README.txt').write_text(REVISIONS[game]+'\nUnity6000.3.26f1\n\n'+launch+'\n'+text+'\n음악은 첫 클릭/터치 이후 재생됩니다. 실제 검증 범위는 RenewalValidation.md를 확인하세요.\n')
 shutil.copyfile(ROOT/'Docs/RenewalValidation.md',folder/'RenewalValidation.md')
 notice=folder/'ThirdParty';notice.mkdir(exist_ok=True)
 for p in (STAGE/'games'/GAMES[game]/'ThirdParty').iterdir():BASE.safe(p);shutil.copyfile(p,notice/p.name)

def player(game,target):
 folder=BUILD/game/target if target=='Windows' else STAGE/'games'/GAMES[game]
 rows={game+'-'+target+'/'+p.relative_to(folder).as_posix():p for p in folder.rglob('*') if p.is_file() and shipping(p.relative_to(folder))}
 if target=='Web':
  for name in ('README.txt','RenewalValidation.md'):rows[game+'-Web/'+name]=BUILD/game/'Web'/name
 return rows

def evidence():
 rows={}
 for folder in (OUT,ROOT/'Tools/Data/Renewal',ROOT/'Tools/Art/GospelRenewal'):
  if folder.exists():
   for p in folder.rglob('*'):
    if p.is_file() and p.suffix.lower() in {'.json','.txt','.md','.sha256','.trx','.xml','.py','.js','.png','.asset'} and p.name not in ('deliverables.json','current-work.json'):rows[p.relative_to(ROOT).as_posix()]=p
 for game in GAMES:
  for p in (ROOT/'Artifacts/Screenshots'/game).glob('renewal-*.png*'):
   if p.is_file():rows[p.relative_to(ROOT).as_posix()]=p
  for target in ('Windows','Web'):
   for name in ('BuildInputs.json','BuildEvidence.txt','LegacyResourceExclusions.json'):
    p=BUILD/game/target/name
    if p.is_file():rows[f'Builds/{game}/{target}/{name}']=p
 for relative in ('Docs/RenewalValidation.md','Tools/Environment/validation.json','Tools/Build/package-renewal.py','Tools/Build/package-modern.py','Tools/Build/renewal-task.sh','Tools/Build/renewal-pipeline-state.py','Tools/Validation/renewal_release_evidence.py','Tools/Validation/summarize-renewal-release.py','Tools/Validation/renewal_player_payload.py','Tools/Validation/run-renewal-native.py','Tools/Validation/renewal-web-smoke.py','Tools/Validation/renewal-smoke-plans.json','Tools/Validation/renewal-public-plans.json','Tools/Validation/verify-public-portal.py','Tools/Validation/recover-public-portal.py','Tools/Web/stage-renewal.py','Tools/Web/release_contract.py'):
  p=ROOT/relative
  if p.is_file():rows[relative]=p
 for relative in ('fm-local-media-errors.py','test-fm-local-media-errors.py','Fixtures/fm-inactive-preloads-48739.json','Fixtures/fm-public-pregesture-ranges.json','Fixtures/fm-public-recovered-ranges.json','Fixtures/fm-renewal-public-range.json'):
  p=ROOT/'Tools/Validation'/relative
  if p.is_file():rows[p.relative_to(ROOT).as_posix()]=p
 return rows

def main():
 p=argparse.ArgumentParser();p.add_argument('--part',choices=('all','verify'),default='all');args=p.parse_args()
 bound=inputs();storage()
 if args.part=='all':
  for game in GAMES:
   for target in ('Windows','Web'):notes(game,target)
 sets={f'{game}-{target}.zip':player(game,target) for game in GAMES for target in ('Windows','Web')}
 sets['FirstGame-UnitySources.zip']=BASE.source_files();sets['FirstGame-RenewalEvidence.zip']=evidence()
 results=[BASE.verify(DEST/name,entries) if args.part=='verify' else BASE.write_archive(name,entries) for name,entries in sets.items()]
 record={'status':'passed','releaseProfile':'renewal','gameRevisions':REVISIONS,'checkedUtc':datetime.now(timezone.utc).isoformat(),'actualRoot':str(DEST),'artifactPath':str(LINK),**bound,'archives':results,'scope':'Six archives: exact current two-game Windows/Web, full sources and fresh evidence; each file set/CRC/SHA/LFS/credential path verified. No unperformed hardware/audio listening claim.'}
 (OUT/'deliverables.json').write_text(json.dumps(record,ensure_ascii=False,indent=2)+'\n');(DEST/'Deliverables.sha256').write_text(''.join(r['sha256']+'  '+r['archive']+'\n' for r in results));print(json.dumps(record,ensure_ascii=False))
if __name__=='__main__':main()
