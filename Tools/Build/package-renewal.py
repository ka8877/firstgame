 rows={}
 for folder in (OUT,ROOT/'Tools/Data/Renewal',ROOT/'Tools/Data/Polish',ROOT/'Tools/Data/GospelChronicle',ROOT/'Tools/Art/GospelRenewal',ROOT/'Tools/Art/GospelRadiance',ROOT/'Tools/Art/GospelChronicle',ROOT/'Tools/Research/FmPolish',ROOT/'Tools/Research/FmChronicle'):
  if folder.exists():
   for p in folder.rglob('*'):
    if p.is_file() and p.suffix.lower() in {'.json','.txt','.md','.sha256','.trx','.xml','.py','.js','.png','.jpg','.jpeg','.asset'} and p.name not in ('deliverables.json','current-work.json'):rows[p.relative_to(ROOT).as_posix()]=p
 for game in GAMES:
  for p in (OUT/'Screenshots'/game).glob('chronicle-*.png*'):
   if p.is_file():rows[p.relative_to(ROOT).as_posix()]=p
  for target in CURRENT_TARGETS:
   for name in ('BuildInputs.json','BuildEvidence.txt','LegacyResourceExclusions.json'):
    p=BUILD/game/target/name
    if p.is_file():rows[f'Builds/{game}/{target}/{name}']=p
 for relative in ('Docs/ChronicleValidation.md','Docs/Chronicle.md','Docs/FmChronicleUI.md','Docs/GospelChronicle.md','Docs/GospelChronicleCharacter.md','Docs/Research/FmChronicleSources.md','Tools/Environment/validation.json','Tools/Build/package-renewal.py','Tools/Build/package-modern.py','Tools/Build/renewal-task.sh','Tools/Build/renewal-pipeline-state.py','Tools/Build/reclaim-chronicle-storage.py','Tools/Build/reclaim-chronicle-generated-cache.py','Tools/Build/reclaim-chronicle-compiler-cache.py','Tools/Build/reclaim-chronicle-historical-player.py','Tools/Validation/chronicle_storage.py','Tools/Validation/run-renewal-core.py','Tools/Validation/renewal_release_evidence.py','Tools/Validation/summarize-renewal-release.py','Tools/Validation/renewal_player_payload.py','Tools/Validation/run-renewal-native.py','Tools/Validation/renewal-web-smoke.py','Tools/Validation/renewal-smoke-plans.json','Tools/Validation/renewal-cards-plan.json','Tools/Validation/renewal-cards-mobile-plan.json','Tools/Validation/renewal-gospel-plan.json','Tools/Validation/renewal-public-plans.json','Tools/Validation/verify-public-portal.py','Tools/Validation/recover-public-portal.py','Tools/Web/stage-renewal.py','Tools/Web/release_contract.py'):
  p=ROOT/relative
  if p.is_file():rows[relative]=p
