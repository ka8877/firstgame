#!/usr/bin/env python3
"""Package only the current Gospel players plus repository sources and Luminous evidence.

Reuses the existing exact-file/CRC/SHA/LFS/credential-path archive verifier.
Never builds, opens a browser, publishes or creates new acceptance gates.
Player notes are prepared before archive inventories; --part verify is read-only
apart from its separate archive verification result/checksum files.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import importlib.util
import json
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'Artifacts/Validation/Luminous'
BUILD = Path('/tmp/firstgame-luminous-builds/PathOfDawn')
STAGE = Path('/tmp/firstgame-luminous-staged-site')
DEST = Path('/tmp/firstgame-luminous-deliverables')
LINK = ROOT / 'Artifacts/LuminousDeliverables'
REVISION = 'gospel-luminous-2026-10-28'
MARKER = 'Generated by Tools/Build/package-luminous.py\n'
spec = importlib.util.spec_from_file_location('luminous_package_base', ROOT / 'Tools/Build/package-modern.py')
BASE = importlib.util.module_from_spec(spec)
spec.loader.exec_module(BASE)
BASE.ART = DEST
BASE.REVISIONS = {'PathOfDawn': REVISION}
BASE.EXCLUDED.update({'.pki', '.cache', '.local', '.npm'})


def read(path):
    return json.loads(Path(path).read_text())


def reference(path):
    path = Path(path)
    return {'file': str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path),
            'bytes': path.stat().st_size, 'sha256': BASE.digest(path)}


def archive_previous(name):
    path = DEST / name
    if path.exists():
        previous = DEST / 'Previous'
        previous.mkdir(exist_ok=True)
        path.rename(previous / (path.stem + '-' + datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ') + path.suffix))


BASE.archive_previous = archive_previous


def shipping(relative):
    # Mono's settings.map is a runtime configuration file, not a source map.
    if relative.name == 'settings.map' and 'MonoBleedingEdge' in relative.parts:
        return True
    return BASE.shipping(relative) and '.symbols.' not in relative.name


def prepare_storage():
    ledger_path = OUT / 'generated-deliverables-storage.json'
    if DEST.exists():
        BASE.require(DEST.is_dir() and not DEST.is_symlink() and
                     (DEST / '.firstgame-luminous-deliverables').read_text() == MARKER,
                     'Unexpected deliverables root; retain it for review')
    if LINK.exists() or LINK.is_symlink():
        BASE.require(LINK.is_symlink() and LINK.readlink() == DEST, 'Unexpected deliverables artifact path')
    expected = {'status': 'prepared', 'artifactPath': str(LINK), 'actualRoot': str(DEST)}
    OUT.mkdir(parents=True, exist_ok=True)
    if ledger_path.exists():
        recorded = read(ledger_path)
        BASE.require(all(recorded.get(key) == value for key, value in expected.items()), 'Deliverables storage ledger differs')
    else:
        # Stable across verification, and recorded before creating the link.
        ledger_path.write_text(json.dumps({**expected, 'preparedUtc': datetime.now(timezone.utc).isoformat(),
            'scope': 'Generated current archives only; original archives/source/evidence are retained.'}, indent=2) + '\n')
    DEST.mkdir(exist_ok=True)
    (DEST / '.firstgame-luminous-deliverables').write_text(MARKER)
    if not LINK.is_symlink():
        LINK.symlink_to(DEST, target_is_directory=True)


def verify_inputs():
    spec = importlib.util.spec_from_file_location('luminous_package_source_binding', ROOT / 'Tools/Validation/restoration_source_binding.py')
    binding = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(binding)
    builds = {}
    for target, platform in (('Windows', 'StandaloneWindows64'), ('Web', 'WebGL')):
        folder = BUILD / target
        evidence_path, inputs_path = folder / 'BuildEvidence.txt', folder / 'BuildInputs.json'
        evidence = dict(line.split(': ', 1) for line in evidence_path.read_text().splitlines() if ': ' in line)
        inputs = read(inputs_path)
        BASE.require(evidence.get('Revision') == REVISION and evidence.get('Result') == 'Succeeded'
                     and evidence.get('Content') == 'gospel-0.1.0' and evidence.get('Target') == platform
                     and evidence.get('Errors') == '0' and evidence.get('LegacyResourcesRestored') == 'true'
                     and inputs.get('game') == 'PathOfDawn' and binding.verify(inputs) == evidence.get('SourceFingerprint'),
                     'Current successful source-bound Gospel build required: ' + target)
        builds[target] = {'evidence': reference(evidence_path), 'inputs': reference(inputs_path),
                          'sourceFingerprint': inputs['fingerprint']}
    BASE.require((BUILD / 'Windows/PathOfDawn.exe').is_file(), 'Current Windows executable missing')
    stage_manifest_path = STAGE / 'build-manifest.json'
    manifest = read(stage_manifest_path)
    BASE.require(manifest.get('releaseProfile') == 'luminous' and manifest.get('publishReady') is True
                 and manifest.get('sourceDirty') is False and manifest.get('gameRevisions', {}).get('PathOfDawn') == REVISION
                 and manifest.get('gameRevisions', {}).get('FantasyCards') == 'fm-restoration-2026-10-27',
                 'Current verified staged release required before packaging')
    for name, expected in manifest['files'].items():
        path = STAGE / name
        BASE.require(path.resolve().is_relative_to(STAGE) and path.is_file() and BASE.digest(path) == expected,
                     'Current staged public bytes changed: ' + name)
        BASE.safe(path)
    stage_game = STAGE / 'games/path-of-dawn'
    runtime = {str(path.relative_to(BUILD / 'Web')): path for path in (BUILD / 'Web').rglob('*') if path.is_file()
               and (path.relative_to(BUILD / 'Web').as_posix() == 'index.html'
                    or path.relative_to(BUILD / 'Web').parts[0] in ('Build', 'StreamingAssets', 'TemplateData'))
               and shipping(path.relative_to(BUILD / 'Web'))}
    staged_runtime = {str(path.relative_to(stage_game)): path for path in stage_game.rglob('*') if path.is_file()
                      and (path.relative_to(stage_game).as_posix() == 'index.html'
                           or path.relative_to(stage_game).parts[0] in ('Build', 'StreamingAssets', 'TemplateData'))}
    BASE.require(runtime and set(runtime) == set(staged_runtime), 'Current and staged Gospel runtime file sets differ')
    for name, path in runtime.items():
        BASE.require(BASE.digest(path) == BASE.digest(staged_runtime[name]), 'Staged Gospel differs from the current build: ' + name)
    required_notices = {
        'LostCrypt-World-SOURCE-NOTICE.txt': ROOT / 'Games/PathOfDawn/Assets/Resources/Art/GospelLuminous/World/SOURCE-NOTICE.txt',
        'LuminousActors-SOURCE-NOTICE.txt': ROOT / 'Games/PathOfDawn/Assets/Resources/Art/GospelLuminous/Actors/SOURCE-NOTICE.txt',
        'LuminousActors-UnityCompanionLicense.txt': ROOT / 'Games/PathOfDawn/Assets/Resources/Art/GospelLuminous/Actors/UnityCompanionLicense.txt',
    }
    for name, source in required_notices.items():
        path = stage_game / 'ThirdParty' / name
        BASE.require(path.is_file() and BASE.digest(path) == BASE.digest(source), 'Current complete notice missing: ' + name)
    source_commit = subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()
    BASE.require(not subprocess.check_output(['git', 'status', '--porcelain'], cwd=ROOT, text=True),
                 'Commit final source and validation notes before packaging')
    return {'sourceCommit': source_commit, 'stagedSourceCommit': manifest['sourceCommit'],
            'stageManifest': reference(stage_manifest_path), 'builds': builds}


def notes(target):
    folder = BUILD / target
    launch = ('압축을 모두 풀고 PathOfDawn.exe를 실행하세요. 데이터 폴더와 DLL도 함께 필요합니다.\n' if target == 'Windows' else
              '폴더 전체를 HTTP/HTTPS 서버에서 실행하세요. file:// 직접 실행은 지원하지 않습니다.\n')
    (folder / 'README.txt').write_text(REVISION + '\nUnity 6000.3.26f1\n\n' + launch +
        '새 여정 시작 즉시 2D 장면을 둘러볼 수 있습니다. 말씀 읽기는 선택해서 시작하며 기존 순서를 따릅니다.\n'
        'A/D 또는 좌우 방향키 이동, Shift 달리기, Space 점프, E 말씀/만남, 휠 확대·축소.\n'
        'I 인물, B 가방, M 말씀 기록, Esc 메뉴/복귀. 모바일은 화면의 누르기·달리기·점프·대화 버튼을 사용합니다.\n'
        '음악은 첫 실제 클릭/터치/키 입력 뒤 재생됩니다. 진행과 등잔 장착은 현재 기기에 저장됩니다.\n'
        '현재 실제 성경 범위는 탄생 도입과 누가복음 2장 성전 방문입니다. 배경과 소지품은 학습용 게임 구성입니다.\n'
        '공식 Lost Crypt 환경 자료와 새 인물/성전 원화를 사용합니다. Ori 상용 소스나 전체 게임을 복구한 결과가 아닙니다.\n'
        '실제 검증 범위와 한계는 동봉 GospelLuminousValidation.md를 확인하세요.\n')
    for source in sorted((ROOT / 'Docs').glob('GospelLuminous*.md')):
        shutil.copyfile(source, folder / source.name)
    notices = folder / 'ThirdParty'
    notices.mkdir(exist_ok=True)
    for source in sorted((STAGE / 'games/path-of-dawn/ThirdParty').iterdir()):
        BASE.require(source.is_file(), 'Unexpected nested/linked notice')
        BASE.safe(source)
        shutil.copyfile(source, notices / source.name)


def player_files(target):
    folder = BUILD / target if target == 'Windows' else STAGE / 'games/path-of-dawn'
    entries = {'PathOfDawn-' + target + '/' + str(path.relative_to(folder)): path
               for path in sorted(folder.rglob('*')) if path.is_file() and shipping(path.relative_to(folder))}
    if target == 'Web':
        # Add instructions outside the immutable published stage. The actual
        # runtime and all third-party notices remain exact published bytes.
        for source in (BUILD / 'Web').iterdir():
            if source.is_file() and (source.name == 'README.txt' or source.name.startswith('GospelLuminous') and source.suffix == '.md'):
                entries['PathOfDawn-Web/' + source.name] = source
    return entries


def evidence_files():
    result = {}
    extensions = {'.json', '.png', '.txt', '.md', '.sha256', '.trx', '.xml', '.py', '.js'}
    for parent in (OUT, ROOT / 'Tools/Art/GospelLuminous'):
        for source in sorted(parent.rglob('*')):
            pipeline_snapshot = source.suffix == '.asset' and source.name in {
                'LuminousDesktopURP.asset', 'LuminousWebURP.asset', 'UniversalRenderPipelineGlobalSettings.asset'}
            if source.is_file() and (source.suffix.lower() in extensions or pipeline_snapshot) and source.name not in {'deliverables.json', 'current-work.json'}:
                result[str(source.relative_to(ROOT))] = source
    # The current native originals live outside OUT. Include the exact six
    # Root-reviewed frames plus this same run's jump frame and their sidecars;
    # unrelated historical screenshot trees remain outside this compact ZIP.
    native_folder = ROOT / 'Artifacts/Screenshots/PathOfDawn'
    native_prefix = 'luminous-NativeFinal14-'
    native_review = OUT / 'Root/native-critical-review.json'
    if native_review.is_file():
        for shot in read(native_review).get('screenshots', []):
            source = ROOT / shot['file']
            BASE.require(source.resolve().parent == native_folder.resolve()
                         and source.name.startswith(native_prefix) and source.suffix == '.png'
                         and BASE.digest(source) == shot['sha256'], 'Current reviewed native original changed')
            result[str(source.relative_to(ROOT))] = source
    for source in sorted(native_folder.glob(native_prefix + '*.png')):
        result[str(source.relative_to(ROOT))] = source
        sidecar = source.with_name(source.name + '.txt')
        if sidecar.is_file():
            result[str(sidecar.relative_to(ROOT))] = sidecar
    for source in sorted((ROOT / 'Docs').glob('GospelLuminous*.md')):
        result[str(source.relative_to(ROOT))] = source
    for relative in ('Tools/Build/package-luminous.py', 'Tools/Build/package-modern.py', 'Tools/Build/luminous-task.sh',
                     'Tools/Build/luminous-pipeline-state.py',
                     'Tools/Validation/luminous-web-smoke.py', 'Tools/Validation/restoration_source_binding.py',
                     'Tools/Validation/webaudio-observer.js', 'Tools/Validation/verify-public-portal.py',
                     'Tools/Web/stage-luminous.py', 'Tools/Web/release_contract.py'):
        source = ROOT / relative
        if source.is_file():
            result[relative] = source
    for target in ('Windows', 'Web'):
        for name in ('BuildEvidence.txt', 'BuildInputs.json', 'LegacyResourceExclusions.json'):
            source = BUILD / target / name
            BASE.require(source.is_file(), 'Missing current build evidence: ' + str(source))
            result['Builds/PathOfDawn/' + target + '/' + name] = source
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--part', choices=('all', 'players', 'source', 'evidence', 'verify'), default='all')
    args = parser.parse_args()
    verified = verify_inputs()
    prepare_storage()
    if args.part in ('all', 'players'):
        for target in ('Windows', 'Web'):
            notes(target)
    sets = {f'PathOfDawn-{target}.zip': player_files(target) for target in ('Windows', 'Web')}
    sets['FirstGame-UnitySources.zip'] = BASE.source_files()
    sets['FirstGame-LuminousEvidence.zip'] = evidence_files()
    selected = list(sets) if args.part in ('all', 'verify') else (
        ['PathOfDawn-Windows.zip', 'PathOfDawn-Web.zip'] if args.part == 'players' else
        ['FirstGame-UnitySources.zip'] if args.part == 'source' else ['FirstGame-LuminousEvidence.zip'])
    rows = [BASE.verify(DEST / name, sets[name]) if args.part == 'verify' else BASE.write_archive(name, sets[name])
            for name in selected]
    if args.part in ('all', 'verify'):
        result = {'status': 'passed', 'releaseProfile': 'luminous', 'revision': REVISION,
                  'checkedUtc': datetime.now(timezone.utc).isoformat(), 'actualRoot': str(DEST), 'artifactPath': str(LINK),
                  **verified, 'archives': rows,
                  'scope': 'Four archives only: current Gospel Windows/Web, repository sources and Luminous evidence. '
                           'Exact file sets/current bytes/CRC/LFS/credential paths verified; no FantasyCards rebuild, '
                           'new browser gate, physical hardware performance or publication check is claimed by packaging.'}
        (OUT / 'deliverables.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
        (DEST / 'Deliverables.sha256').write_text(''.join(row['sha256'] + '  ' + row['archive'] + '\n' for row in rows))
    print(json.dumps({'status': 'passed', 'part': args.part, 'actualRoot': str(DEST), 'archives': rows}))


if __name__ == '__main__':
    try:
        main()
    except (AssertionError, KeyError, ValueError, OSError, subprocess.CalledProcessError) as error:
        raise SystemExit('Luminous package refused: ' + str(error))
